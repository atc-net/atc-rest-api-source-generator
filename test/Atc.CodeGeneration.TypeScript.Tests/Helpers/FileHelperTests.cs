namespace Atc.CodeGeneration.TypeScript.Tests.Helpers;

public class FileHelperTests
{
    [Fact]
    public void WriteTsFile_MissingDirectory_CreatesItAndWritesTrimmedUtf8WithoutBom()
    {
        // Arrange
        var root = Path.Combine(Path.GetTempPath(), "atc-ts-" + Guid.NewGuid().ToString("N", System.Globalization.CultureInfo.InvariantCulture));
        var filePath = Path.Combine(root, "models", "pet.ts");

        try
        {
            // Act
            FileHelper.WriteTsFile(filePath, "export interface Pet { name: string; }   \n\n");

            // Assert
            Assert.True(File.Exists(filePath));
            Assert.Equal("export interface Pet { name: string; }", File.ReadAllText(filePath));

            var bytes = File.ReadAllBytes(filePath);
            Assert.False(bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF);
        }
        finally
        {
            if (Directory.Exists(root))
            {
                Directory.Delete(root, recursive: true);
            }
        }
    }

    [Fact]
    public void WriteTsFile_SameContent_LeavesTheFileUntouched()
    {
        // A watcher or bundler that sees every file written would rebuild everything on each regeneration
        var root = Path.Combine(Path.GetTempPath(), "atc-ts-" + Guid.NewGuid().ToString("N", System.Globalization.CultureInfo.InvariantCulture));
        var filePath = Path.Combine(root, "pet.ts");

        try
        {
            FileHelper.WriteTsFile(filePath, "export interface Pet { name: string; }\n");
            var past = new DateTime(2020, 1, 1, 0, 0, 0, DateTimeKind.Utc);
            File.SetLastWriteTimeUtc(filePath, past);

            Assert.False(FileHelper.WriteTsFile(filePath, "export interface Pet { name: string; }\n"));
            Assert.Equal(past, File.GetLastWriteTimeUtc(filePath));

            Assert.True(FileHelper.WriteTsFile(filePath, "export interface Pet { name: string; tag?: string; }\n"));
            Assert.NotEqual(past, File.GetLastWriteTimeUtc(filePath));
        }
        finally
        {
            if (Directory.Exists(root))
            {
                Directory.Delete(root, recursive: true);
            }
        }
    }

    [Fact]
    public void WriteTsFile_MixedLineEndings_WritesLfOnly()
    {
        // A header built with \n and a body built with AppendLine (\r\n on Windows) must not reach the file as a mix
        var root = Path.Combine(Path.GetTempPath(), "atc-ts-" + Guid.NewGuid().ToString("N", System.Globalization.CultureInfo.InvariantCulture));
        var filePath = Path.Combine(root, "shade.ts");

        try
        {
            FileHelper.WriteTsFile(filePath, "// <auto-generated />\n// tool\r\nexport type Shade = 'LIGHT';\r\n\rexport const x = 1;\r\n");

            Assert.Equal("// <auto-generated />\n// tool\nexport type Shade = 'LIGHT';\n\nexport const x = 1;", File.ReadAllText(filePath));
        }
        finally
        {
            if (Directory.Exists(root))
            {
                Directory.Delete(root, recursive: true);
            }
        }
    }

    [Fact]
    public void WriteTsFile_AFileThatDiffersOnlyInLineEndings_IsLeftUntouched()
    {
        // git with core.autocrlf=true checks the files out with CRLF: git sees no change in a regeneration, so neither
        // should a watcher or bundler
        var root = Path.Combine(Path.GetTempPath(), "atc-ts-" + Guid.NewGuid().ToString("N", System.Globalization.CultureInfo.InvariantCulture));
        var filePath = Path.Combine(root, "pet.ts");

        try
        {
            Directory.CreateDirectory(root);
            File.WriteAllText(filePath, "// a\r\nexport const x = 1;");
            var past = new DateTime(2020, 1, 1, 0, 0, 0, DateTimeKind.Utc);
            File.SetLastWriteTimeUtc(filePath, past);

            Assert.False(FileHelper.WriteTsFile(filePath, "// a\nexport const x = 1;\n"));
            Assert.Equal(past, File.GetLastWriteTimeUtc(filePath));
            Assert.Equal("// a\r\nexport const x = 1;", File.ReadAllText(filePath));

            Assert.True(FileHelper.WriteTsFile(filePath, "// a\nexport const x = 2;\n"));
            Assert.Equal("// a\nexport const x = 2;", File.ReadAllText(filePath));
        }
        finally
        {
            if (Directory.Exists(root))
            {
                Directory.Delete(root, recursive: true);
            }
        }
    }

    [Fact]
    public void WriteTsFile_AFileWithMixedLineEndingsAndTheSameText_IsRewrittenWithLf()
    {
        // Only a uniform checkout is left as it is; a mix (what an older tool wrote) is repaired on the next run
        var root = Path.Combine(Path.GetTempPath(), "atc-ts-" + Guid.NewGuid().ToString("N", System.Globalization.CultureInfo.InvariantCulture));
        var filePath = Path.Combine(root, "pet.ts");

        try
        {
            Directory.CreateDirectory(root);
            File.WriteAllText(filePath, "// a\n// b\r\nexport const x = 1;");

            Assert.True(FileHelper.WriteTsFile(filePath, "// a\n// b\nexport const x = 1;\n"));
            Assert.Equal("// a\n// b\nexport const x = 1;", File.ReadAllText(filePath));
        }
        finally
        {
            if (Directory.Exists(root))
            {
                Directory.Delete(root, recursive: true);
            }
        }
    }

    [Fact]
    public void WriteTsFile_EmptyPath_Throws()
        => Assert.Throws<ArgumentNullException>(() => FileHelper.WriteTsFile(string.Empty, "x"));
}