namespace Atc.Rest.Api.Generator.Cli.Tests.Services;

public sealed class TypeScriptEmitWriterTests : IDisposable
{
    private const string Header = "// <auto-generated />\n";

    private readonly string output = Path.Combine(Path.GetTempPath(), "atc-ts-emit", Guid.NewGuid().ToString("N"));

    [Fact]
    public void Write_AddedTwice_WritesTheLastContent()
    {
        // Arrange
        var plan = new TypeScriptEmitPlan();
        plan.Add("types/index.ts", Header + "export type * from './ApiResult';\n");
        plan.Add("types/index.ts", Header + "export type * from './ApiResult';\nexport type * from './BrandedIds';\n");

        // Act
        TypeScriptEmitWriter.Write(plan, output, removeStale: false);

        // Assert
        Assert.Single(plan.Files);
        Assert.EndsWith("export type * from './BrandedIds';", File.ReadAllText(Path.Combine(output, "types", "index.ts")), StringComparison.Ordinal);
    }

    [Fact]
    public void Write_AFileWithoutTheGeneratedHeader_IsKeptAndReported()
    {
        // Arrange
        var own = Path.Combine(output, "models", "Pet.ts");
        Directory.CreateDirectory(Path.GetDirectoryName(own)!);
        File.WriteAllText(own, "export interface Pet { name: string }\n");
        var plan = new TypeScriptEmitPlan();
        plan.Add("models/Pet.ts", Header + "export interface Pet { id: number }\n");
        plan.Add("models/Owner.ts", Header + "export interface Owner { id: number }\n");

        // Act
        var kept = TypeScriptEmitWriter.Write(plan, output, removeStale: true);

        // Assert
        Assert.Equal(["models/Pet.ts"], kept);
        Assert.Equal("export interface Pet { name: string }\n", File.ReadAllText(own));
        Assert.True(File.Exists(Path.Combine(output, "models", "Owner.ts")));
    }

    [Fact]
    public void Write_AScaffoldFile_IsWrittenWithLfLineEndings()
    {
        // Arrange
        var plan = new TypeScriptEmitPlan();
        plan.AddScaffold("package.json", "{\r\n  \"name\": \"generated\"\n}\r\n");

        // Act
        TypeScriptEmitWriter.Write(plan, output, removeStale: false);

        // Assert
        Assert.Equal("{\n  \"name\": \"generated\"\n}\n", File.ReadAllText(Path.Combine(output, "package.json")));
    }

    [Fact]
    public void Write_AScaffoldFileThatExists_IsNotRewritten()
    {
        // Arrange
        var packageJson = Path.Combine(output, "package.json");
        Directory.CreateDirectory(output);
        File.WriteAllText(packageJson, "{ \"name\": \"mine\" }");
        var plan = new TypeScriptEmitPlan();
        plan.AddScaffold("package.json", "{ \"name\": \"generated\" }");
        plan.AddScaffold("scripts/postbuild-cjs.mjs", "// postbuild");

        // Act
        TypeScriptEmitWriter.Write(plan, output, removeStale: false);

        // Assert
        Assert.Equal("{ \"name\": \"mine\" }", File.ReadAllText(packageJson));
        Assert.Equal("// postbuild", File.ReadAllText(Path.Combine(output, "scripts", "postbuild-cjs.mjs")));
    }

    [Theory]
    [InlineData(true, false)]
    [InlineData(false, true)]
    public void Write_AGeneratedFileThePlanNoLongerHas_IsRemovedOnlyWithRemoveStale(
        bool removeStale,
        bool expectedToExist)
    {
        // Arrange
        var stale = Path.Combine(output, "models", "Owner.ts");
        var handWritten = Path.Combine(output, "models", "extensions.ts");
        var otherFolder = Path.Combine(output, "enums", "Colour.ts");
        Directory.CreateDirectory(Path.GetDirectoryName(stale)!);
        Directory.CreateDirectory(Path.GetDirectoryName(otherFolder)!);
        File.WriteAllText(stale, Header + "export interface Owner { id: number }\n");
        File.WriteAllText(handWritten, "export const answer = 42;\n");
        File.WriteAllText(otherFolder, Header + "export type Colour = 'red';\n");
        var plan = new TypeScriptEmitPlan();
        plan.Add("models/Pet.ts", Header + "export interface Pet { id: number }\n");

        // Act
        TypeScriptEmitWriter.Write(plan, output, removeStale);

        // Assert
        Assert.Equal(expectedToExist, File.Exists(stale));
        Assert.True(File.Exists(handWritten), "a file without the generated header is never removed");
        Assert.True(File.Exists(otherFolder), "a folder the plan does not write to is left alone");
    }

    public void Dispose()
    {
        if (Directory.Exists(output))
        {
            Directory.Delete(output, recursive: true);
        }
    }
}