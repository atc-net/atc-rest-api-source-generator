namespace Atc.Rest.Api.Generator.Cli.Tests.Extractors.TypeScript;

public class TypeScriptDownloadHelperExtractorTests
{
    [Fact]
    public void Generate_ExportsGetDownloadFileName_ReadingBothContentDispositionForms()
    {
        var content = TypeScriptDownloadHelperExtractor.Generate(headerContent: null);

        Assert.Contains("export function getDownloadFileName(response: { headers: unknown }): string | undefined {", content, StringComparison.Ordinal);

        // RFC 5987 `filename*` is tried first, then the plain `filename`, else undefined.
        Assert.Contains("filename\\*", content, StringComparison.Ordinal);
        Assert.Contains("decodeURIComponent(extended.trim())", content, StringComparison.Ordinal);
        Assert.Contains("/filename\\s*=\\s*", content, StringComparison.Ordinal);
        Assert.Contains("return value !== undefined ? value.trim() : undefined;", content, StringComparison.Ordinal);

        // The Fetch Headers object and the Axios plain header record are both read.
        Assert.Contains("typeof headers?.get === 'function'", content, StringComparison.Ordinal);
        Assert.Contains("headers?.['content-disposition'] ?? headers?.['Content-Disposition']", content, StringComparison.Ordinal);
    }

    [Fact]
    public void Generate_WithHeader_PrependsItVerbatim()
    {
        const string header = "// <auto-generated/>\n";

        var content = TypeScriptDownloadHelperExtractor.Generate(header);

        Assert.StartsWith(header + "/**", content, StringComparison.Ordinal);
    }
}