namespace Atc.Rest.Api.Generator.Tests.Extractors;

public class SequentialResultsExtractorTests
{
    [Theory]
    [InlineData("application/jsonl", true)]
    [InlineData("application/json-seq", true)]
    [InlineData("multipart/mixed", true)]
    [InlineData("text/event-stream", true)]
    public void DocumentRequiresSequentialResults_StreamingMediaType_EveryStreamNeedsTheHelper(
        string mediaType,
        bool expected)
    {
        var document = OpenApiDocumentHelper.ParseYaml(BuildStreamingDocument(mediaType));

        Assert.Equal(expected, SequentialResultsExtractor.DocumentRequiresSequentialResults(document));
    }

    [Fact]
    public void DocumentRequiresSequentialResults_LegacyJsonArrayStreaming_ReturnsTrue()
    {
        var document = OpenApiDocumentHelper.ParseYaml(
            """
            openapi: 3.0.0
            info:
              title: Test
              version: 1.0.0
            paths:
              /events:
                get:
                  operationId: streamEvents
                  x-return-async-enumerable: true
                  responses:
                    '200':
                      description: OK
                      content:
                        application/json:
                          schema:
                            type: array
                            items:
                              $ref: '#/components/schemas/Event'
            components:
              schemas:
                Event:
                  type: object
                  properties:
                    id:
                      type: string
            """);

        Assert.True(SequentialResultsExtractor.DocumentRequiresSequentialResults(document));
    }

    [Fact]
    public void DocumentRequiresSequentialResults_NoPaths_ReturnsFalse()
    {
        var document = OpenApiDocumentHelper.ParseYaml(
            """
            openapi: 3.0.0
            info:
              title: Test
              version: 1.0.0
            paths: {}
            """);

        Assert.False(SequentialResultsExtractor.DocumentRequiresSequentialResults(document));
    }

    [Fact]
    public void GenerateContent_EmitsWriterAndResultTypesInStreamingNamespace()
    {
        var content = SequentialResultsExtractor.GenerateContent("MyApi");

        Assert.StartsWith("// <auto-generated />", content, StringComparison.Ordinal);
        Assert.Contains("namespace MyApi.Generated.Streaming;", content, StringComparison.Ordinal);
        Assert.Contains("public static class SequentialStreamWriter", content, StringComparison.Ordinal);
        Assert.Contains("public const string MultipartBoundary = \"atc-stream-boundary\";", content, StringComparison.Ordinal);
        Assert.Contains("public static async Task WriteJsonLinesAsync<T>(", content, StringComparison.Ordinal);
        Assert.Contains("public static async Task WriteJsonSequenceAsync<T>(", content, StringComparison.Ordinal);
        Assert.Contains("public static async Task WriteMultipartMixedAsync<T>(", content, StringComparison.Ordinal);
        Assert.Contains("public sealed class JsonLinesResult<T> : IResult", content, StringComparison.Ordinal);
        Assert.Contains("public sealed class JsonSequenceResult<T> : IResult", content, StringComparison.Ordinal);
        Assert.Contains("public sealed class MultipartMixedResult<T> : IResult", content, StringComparison.Ordinal);
    }

    [Fact]
    public void GenerateContent_ResultsSetContentTypeAndUseConfiguredJsonOptions()
    {
        var content = SequentialResultsExtractor.GenerateContent("MyApi");

        // The declared media type (application/x-ndjson, application/geo+json-seq) when it is not the writer's default
        Assert.Contains(": this(items, \"application/jsonl\")", content, StringComparison.Ordinal);
        Assert.Contains(": this(items, \"application/json-seq\")", content, StringComparison.Ordinal);
        Assert.Contains("httpContext.Response.ContentType = contentType;", content, StringComparison.Ordinal);
        Assert.Contains("httpContext.Response.ContentType = $\"multipart/mixed; boundary={SequentialStreamWriter.MultipartBoundary}\";", content, StringComparison.Ordinal);
        Assert.Contains(".GetRequiredService<IOptions<JsonOptions>>()", content, StringComparison.Ordinal);

        // RFC 7464: a record separator before each record; the separators are written async (Kestrel forbids sync IO)
        Assert.Contains("private static readonly byte[] RecordSeparator = { 0x1E };", content, StringComparison.Ordinal);
        Assert.Contains("await stream.WriteAsync(RecordSeparator, cancellationToken);", content, StringComparison.Ordinal);
        Assert.DoesNotContain("stream.WriteByte(", content, StringComparison.Ordinal);
    }

    [Fact]
    public void MultipartBoundaryValue_MatchesEmittedConstant()
        => Assert.Equal("atc-stream-boundary", SequentialResultsExtractor.MultipartBoundaryValue);

    private static string BuildStreamingDocument(string mediaType)
        => $"""
            openapi: 3.2.0
            info:
              title: Test
              version: 1.0.0
            paths:
              /events:
                get:
                  operationId: streamEvents
                  responses:
                    '200':
                      description: OK
                      content:
                        {mediaType}:
                          itemSchema:
                            $ref: '#/components/schemas/Event'
            components:
              schemas:
                Event:
                  type: object
                  properties:
                    id:
                      type: string
            """;
}