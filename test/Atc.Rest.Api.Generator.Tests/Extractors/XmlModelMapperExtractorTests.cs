    // The emitters mix raw literals (LF) and StringBuilder.AppendLine (the platform newline); compare on LF
    private static string Lf(string content)
        => content.Replace("\r\n", "\n", StringComparison.Ordinal);

    private static (XmlModelSource Source, HashSet<string> XmlModels) BuildSource(
        string yaml,
        string schemaKey)
    {
        var document = OpenApiDocumentHelper.ParseYaml(yaml);
        var xmlModels = XmlBodyReachability.Collect(document);
        var sources = new List<XmlModelSource>();

        SchemaExtractor.ExtractForSchemasWithInlineEnums(
            document,
            "TestApi",
            new HashSet<string>(document.Components!.Schemas!.Keys, StringComparer.Ordinal),
            pathSegment: null,
            xmlModels: xmlModels,
            xmlSources: sources);

        return (sources.Single(s => s.SchemaKey == schemaKey), xmlModels);
    }
