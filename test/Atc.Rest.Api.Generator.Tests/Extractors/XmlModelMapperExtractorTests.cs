    [Fact]
    public void GenerateCompanion_RootNamesAndEntryPoints_FollowTheXmlKeyword()
    {
        var (source, xmlModels) = BuildSource(PetYaml, "Pet");

        var content = Lf(XmlModelMapperExtractor.GenerateCompanion(source, headerContent: null, "TestApi.Generated.Models", "TestApi", xmlModels));

        Assert.StartsWith("// <auto-generated />\n#nullable enable\n\n", content, StringComparison.Ordinal);
        Assert.Contains("namespace TestApi.Generated.Models;", content, StringComparison.Ordinal);
        Assert.Contains("public static class PetXml", content, StringComparison.Ordinal);
        Assert.Contains("public const string ElementName = \"pet\";", content, StringComparison.Ordinal);
        Assert.Contains("public const string ElementNamespace = \"\";", content, StringComparison.Ordinal);
        Assert.Contains("public const string ListElementName = \"ArrayOfPet\";", content, StringComparison.Ordinal);
        Assert.Contains($"public static string ToXml(Pet value)\n        => {Support}.ToXml(writer => Write(writer, value));", content, StringComparison.Ordinal);
        Assert.Contains($"public static Pet FromXml(string xml)\n        => Read({Support}.Parse(xml));", content, StringComparison.Ordinal);
        Assert.Contains("public static void Write(global::System.Xml.XmlWriter writer, Pet value)\n        => WriteElement(writer, value, ElementName, ElementNamespace, null);", content, StringComparison.Ordinal);
        Assert.Contains("public static global::System.Collections.Generic.List<Pet> ReadList(global::System.Xml.Linq.XElement element)", content, StringComparison.Ordinal);
    }

