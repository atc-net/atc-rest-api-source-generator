    [Fact]
    public void XmlNameOverrides_ReturnsOnlyPropertiesWhoseXmlNameDiffers()
    {
        var (source, xmlModels) = BuildSource(PetYaml, "Pet");

        var overrides = XmlModelMapperExtractor.XmlNameOverrides(source, xmlModels);

        // id is an attribute but keeps its name; tags is wrapped so its element name is the property name
