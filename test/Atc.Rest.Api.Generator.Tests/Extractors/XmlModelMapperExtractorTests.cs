        Assert.Contains("static global::System.Collections.Generic.List<Pet> global::TestApi.Generated.IXmlRequestBody<Pet>.ReadXmlList(global::System.Xml.Linq.XElement element)\n        => PetXml.ReadList(element);", content, StringComparison.Ordinal);
