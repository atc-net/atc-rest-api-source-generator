    [Fact]
    public void GenerateCompanion_WriteElement_AttributesFirstThenElementsWithMappedNames()
    {
        var (source, xmlModels) = BuildSource(PetYaml, "Pet");

        var content = Lf(XmlModelMapperExtractor.GenerateCompanion(source, headerContent: null, "TestApi.Generated.Models", "TestApi", xmlModels));

        Assert.Contains("public static void WriteElement(global::System.Xml.XmlWriter writer, Pet value, string localName, string ns, string? prefix)", content, StringComparison.Ordinal);

        // The two attributes come first (the required long formatted by XmlConvert, the optional string guarded)
        Assert.Contains($"var v1 = value.Id;\n        {Support}.WriteAttribute(writer, \"id\", \"\", null, global::System.Xml.XmlConvert.ToString(v1));", content, StringComparison.Ordinal);
        Assert.Contains($"if (value.Sku is {{ }} v2)\n        {{\n            {Support}.WriteAttribute(writer, \"code\", \"\", null, v2);\n        }}", content, StringComparison.Ordinal);

        // Elements: the renamed text, the enum through its helper, the wrapped and the unwrapped list
        Assert.Contains($"var v3 = value.Name;\n        if (v3 is not null) {{ {Support}.WriteValue(writer, \"petName\", childNamespace, null, v3); }}", content, StringComparison.Ordinal);
        Assert.Contains($"{Support}.WriteValue(writer, \"status\", childNamespace, null, FormatStatus(v4));", content, StringComparison.Ordinal);
        Assert.Contains("writer.WriteStartElement(null, \"tags\", childNamespace);\n            foreach (var item in v5)", content, StringComparison.Ordinal);
        Assert.Contains($"if (item is not null) {{ {Support}.WriteValue(writer, \"tag\", childNamespace, null, item); }}", content, StringComparison.Ordinal);
        Assert.Contains($"foreach (var item in v6)\n            {{\n                if (item is not null) {{ {Support}.WriteValue(writer, \"alias\", childNamespace, null, item); }}\n            }}\n        }}", content, StringComparison.Ordinal);
    }

