    {
        var document = OpenApiDocumentHelper.ParseYaml(PetYaml);
        var bound = XmlBodyHelper.ServerBoundRequestModels(document)["Pet"];
        Assert.Equal(new ServerBoundModel(AcceptsJson: true, BoundAlone: true, BoundInList: true), bound);

        var content = Lf(XmlModelMapperExtractor.GenerateBinding("Pet", "TestApi.Generated.Models", "TestApi", bound));

        Assert.Contains("namespace TestApi.Generated.Models;", content, StringComparison.Ordinal);
        Assert.Contains("/// Binds <see cref=\"Pet\"/> from the request body by its Content-Type (alone (application/json or XML) and in a list).", content, StringComparison.Ordinal);
