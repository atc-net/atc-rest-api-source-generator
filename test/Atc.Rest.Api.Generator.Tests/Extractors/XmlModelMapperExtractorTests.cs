        Assert.Contains("public static async global::System.Threading.Tasks.ValueTask<Pet?> BindAsync(", content, StringComparison.Ordinal);
        Assert.Contains($"if ({Support}.IsXmlMediaType(mediaType))", content, StringComparison.Ordinal);
        Assert.Contains($"return PetXml.Read(await {Support}.LoadAsync(request.Body, context.RequestAborted).ConfigureAwait(false));", content, StringComparison.Ordinal);
        Assert.Contains("if (global::Microsoft.AspNetCore.Http.HttpRequestJsonExtensions.HasJsonContentType(request))", content, StringComparison.Ordinal);
