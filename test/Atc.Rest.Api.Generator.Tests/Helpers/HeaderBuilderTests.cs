namespace Atc.Rest.Api.Generator.Tests.Helpers;

public class HeaderBuilderTests
{
    [Fact]
    public void Constants_AreTheAutoGeneratedCommentAndTheNullableDirective()
    {
        Assert.Equal("// <auto-generated />", HeaderBuilder.AutoGeneratedComment);
        Assert.Equal("#nullable enable", HeaderBuilder.NullableEnable);
    }

    [Fact]
    public void Simple_IsCommentAndNullableDirectiveWithoutUsings()
    {
        var expected = "// <auto-generated />" + Environment.NewLine + "#nullable enable" + Environment.NewLine;

        Assert.Equal(expected, HeaderBuilder.Simple);
    }

    [Fact]
    public void WithUsings_OrdersSystemMicrosoftAspAtcFluentValidationPollyThenCustom()
    {
        var header = HeaderBuilder.WithUsings(
            "Polly",
            "MyApi.Generated.Models",
            "Microsoft.AspNetCore.Http",
            "System.Threading",
            "System",
            "FluentValidation",
            "Atc.Rest.Client",
            "Asp.Versioning");

        var expected =
            "// <auto-generated />" + Environment.NewLine +
            "#nullable enable" + Environment.NewLine +
            Environment.NewLine +
            "using System;" + Environment.NewLine +
            "using System.Threading;" + Environment.NewLine +
            "using Microsoft.AspNetCore.Http;" + Environment.NewLine +
            "using Asp.Versioning;" + Environment.NewLine +
            "using Atc.Rest.Client;" + Environment.NewLine +
            "using FluentValidation;" + Environment.NewLine +
            "using Polly;" + Environment.NewLine +
            "using MyApi.Generated.Models;" + Environment.NewLine +
            Environment.NewLine;
        Assert.Equal(expected, header);
    }

    [Fact]
    public void WithUsings_NoUsings_LeavesTheUsingBlockEmpty()
    {
        var header = HeaderBuilder.WithUsings();

        var expected =
            "// <auto-generated />" + Environment.NewLine +
            "#nullable enable" + Environment.NewLine +
            Environment.NewLine +
            Environment.NewLine;
        Assert.Equal(expected, header);
    }

    [Fact]
    public void ForValidatorDependencyInjection_ImportsCodeDomDependencyInjectionAndFluentValidation()
    {
        var header = HeaderBuilder.ForValidatorDependencyInjection();

        var expected =
            "// <auto-generated />" + Environment.NewLine +
            "#nullable enable" + Environment.NewLine +
            Environment.NewLine +
            "using System.CodeDom.Compiler;" + Environment.NewLine +
            "using Microsoft.Extensions.DependencyInjection;" + Environment.NewLine +
            "using FluentValidation;" + Environment.NewLine +
            Environment.NewLine;
        Assert.Equal(expected, header);
    }
}