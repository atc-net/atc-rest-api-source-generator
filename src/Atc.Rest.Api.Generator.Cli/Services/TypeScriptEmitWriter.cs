namespace Atc.Rest.Api.Generator.Cli.Services;

/// <summary>
/// Writes a <see cref="TypeScriptEmitPlan"/> to the output folder.
/// </summary>
public static class TypeScriptEmitWriter
{
    /// <summary>
    /// Writes the plan's files. A file that exists without the generated header (while its content carries it) is
    /// somebody's own: it is kept and reported. A scaffold file that exists is the user's and is not rewritten. With
    /// <paramref name="removeStale"/>, the files with the generated header that the plan does not have are removed
    /// from the folders it writes to (not their subfolders).
    /// </summary>
    /// <param name="plan">The files to write.</param>
    /// <param name="outputPath">The output folder.</param>
    /// <param name="removeStale">Whether to remove the generated files the plan no longer has.</param>
    /// <returns>The kept files, by their path in the output folder (with <c>/</c> between folders).</returns>
    public static IReadOnlyList<string> Write(
        TypeScriptEmitPlan plan,
        string outputPath,
        bool removeStale)
    {
        ArgumentNullException.ThrowIfNull(plan);
        ArgumentException.ThrowIfNullOrEmpty(outputPath);

        var written = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var kept = new List<string>();

        foreach (var file in plan.Files)
        {
            var filePath = Path.GetFullPath(Path.Combine(outputPath, file.RelativePath));
            if (file.IsScaffold)
            {
                if (File.Exists(filePath))
                {
                    continue;
                }

                var directory = Path.GetDirectoryName(filePath);
                if (!string.IsNullOrEmpty(directory))
                {
                    Directory.CreateDirectory(directory);
                }

                CodeGeneration.TypeScript.Helpers.FileHelper.WriteTextFile(filePath, file.Content);
                written.Add(filePath);
                continue;
            }

            if (File.Exists(filePath) &&
                file.Content.StartsWith(TypeScriptHeaderBuilder.AutoGeneratedHeader, StringComparison.Ordinal) &&
                !StartsWithGeneratedHeader(filePath))
            {
                kept.Add(Path.GetRelativePath(outputPath, filePath).Replace('\\', '/'));
                continue;
            }

            CodeGeneration.TypeScript.Helpers.FileHelper.WriteTsFile(filePath, file.Content);
            written.Add(filePath);
        }

        if (removeStale)
        {
            RemoveStaleGeneratedFiles(written);
        }

        return kept;
    }

    // The TypeScript files with the generated header that this run did not write, in the folders it wrote to (never a
    // file without the header - a hand-written file stays)
    private static void RemoveStaleGeneratedFiles(HashSet<string> written)
    {
        var folders = written
            .Select(Path.GetDirectoryName)
            .OfType<string>()
            .Distinct(StringComparer.OrdinalIgnoreCase);

        foreach (var folder in folders)
        {
            foreach (var file in Directory.EnumerateFiles(folder, "*.ts", SearchOption.TopDirectoryOnly))
            {
                if (!written.Contains(Path.GetFullPath(file)) && StartsWithGeneratedHeader(file))
                {
                    File.Delete(file);
                }
            }
        }
    }

    private static bool StartsWithGeneratedHeader(string filePath)
    {
        using var reader = new StreamReader(filePath);
        return string.Equals(reader.ReadLine()?.Trim(), TypeScriptHeaderBuilder.AutoGeneratedHeader.Trim(), StringComparison.Ordinal);
    }
}