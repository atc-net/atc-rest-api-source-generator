namespace Atc.Rest.Api.Generator.Helpers;

/// <summary>
/// Writes a generated <c>static class</c> of policy name constants - the one shape the output cache, hybrid cache,
/// rate limit, resilience and security policy extractors all emit - so the five share one skeleton.
/// </summary>
public static class PolicyConstantsClassBuilder
{
    /// <summary>
    /// Writes the file header, the namespace, the class and one documented constant per policy, in the order given.
    /// </summary>
    /// <param name="builder">The builder to write to.</param>
    /// <param name="projectName">The project name (root namespace).</param>
    /// <param name="namespaceSuffix">The namespace below <c>{project}.Generated</c>, e.g. <c>Caching</c>.</param>
    /// <param name="className">The class name, e.g. <c>OutputCachePolicies</c>.</param>
    /// <param name="classSummary">The class's summary line.</param>
    /// <param name="constants">The constants, in the order they are written.</param>
    /// <returns><see langword="true"/> when at least one constant was written (the caller closes the class after any extra members).</returns>
    public static bool AppendClass(
        StringBuilder builder,
        string projectName,
        string namespaceSuffix,
        string className,
        string classSummary,
        IEnumerable<PolicyConstant> constants)
    {
        if (builder is null)
        {
            throw new ArgumentNullException(nameof(builder));
        }

        if (constants is null)
        {
            throw new ArgumentNullException(nameof(constants));
        }

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("using System.CodeDom.Compiler;");
        builder.AppendLine();
        builder.AppendLine($"namespace {projectName}.Generated.{namespaceSuffix};");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine($"/// {classSummary}");
        builder.AppendLine("/// </summary>");
        builder.AppendLine($"[GeneratedCode(\"{GeneratorInfo.Name}\", \"{GeneratorInfo.Version}\")]");
        builder.AppendLine($"public static class {className}");
        builder.AppendLine("{");

        var any = false;
        foreach (var constant in constants)
        {
            if (any)
            {
                builder.AppendLine();
            }

            any = true;
            builder.AppendLine(4, "/// <summary>");
            builder.AppendLine(4, $"/// {constant.Description}");
            builder.AppendLine(4, "/// </summary>");
            if (constant.Attribute is not null)
            {
                builder.AppendLine(4, constant.Attribute);
            }

            builder.AppendLine(4, $"public const string {constant.ConstantName} = \"{constant.PolicyName}\";");
        }

        return any;
    }

    /// <summary>
    /// The whole file: <see cref="AppendClass"/> and the closing brace.
    /// </summary>
    /// <param name="projectName">The project name (root namespace).</param>
    /// <param name="namespaceSuffix">The namespace below <c>{project}.Generated</c>.</param>
    /// <param name="className">The class name.</param>
    /// <param name="classSummary">The class's summary line.</param>
    /// <param name="constants">The constants, in the order they are written.</param>
    /// <returns>The file content.</returns>
    public static string Build(
        string projectName,
        string namespaceSuffix,
        string className,
        string classSummary,
        IEnumerable<PolicyConstant> constants)
    {
        var builder = new StringBuilder();
        AppendClass(builder, projectName, namespaceSuffix, className, classSummary, constants);
        builder.AppendLine("}");
        return builder.ToString();
    }
}