    /// <param name="openApiDoc">The OpenAPI document.</param>
    /// <returns>True when the server needs <c>TextRequestBody</c>.</returns>
    public static bool DocumentHasTextRequestBody(OpenApiDocument openApiDoc)
        => openApiDoc
            .GetAllOperationsAndWebhooks()
            .Any(operation => operation.GetTextRequestBodyMediaType() is not null);

