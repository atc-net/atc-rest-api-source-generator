namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// Extracts security configuration and generates DI extension method for authorization policies.
/// </summary>
public static class SecurityDependencyInjectionExtractor
{
    /// <summary>
    /// Extracts security DI registration from OpenAPI document.
    /// </summary>
    /// <param name="openApiDoc">The OpenAPI document.</param>
    /// <param name="projectName">The project name for namespace.</param>
    /// <param name="includeDeprecated">Whether to include deprecated operations.</param>
    /// <returns>Generated code content for the security DI extension class, or null if the document has no security schemes.</returns>
    public static string? Extract(
        OpenApiDocument openApiDoc,
        string projectName,
        bool includeDeprecated = false)
    {
        if (openApiDoc is null)
        {
            throw new ArgumentNullException(nameof(openApiDoc));
        }

        // The unified Add{Project}Api() references AddApiSecurityPolicies() whenever a scheme
        // exists, so the method has to exist then too - even with no policy to register.
        if (!openApiDoc.HasSecuritySchemes())
        {
            return null;
        }

        // Collect all unique policies from security requirements
        var (policies, _, _, _, anyOfPolicies) = SecurityPoliciesExtractor.CollectPolicies(openApiDoc, includeDeprecated);

        // Generate the complete file content
        return GenerateFileContent(projectName, policies, anyOfPolicies);
    }

    /// <summary>
    /// Generates the complete file content.
    /// </summary>
    private static string GenerateFileContent(
        string projectName,
        Dictionary<string, List<string>> policies,
        Dictionary<string, List<SecurityPoliciesExtractor.PolicyAlternative>> anyOfPolicies)
    {
        var hasPolicies = policies.Count > 0 || anyOfPolicies.Count > 0;

        // Build header with only required usings
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        if (hasPolicies)
        {
            builder.AppendLine("using System;");
        }

        builder.AppendLine("using System.CodeDom.Compiler;");
        if (hasPolicies)
        {
            builder.AppendLine("using System.Security.Claims;");
        }

        if (anyOfPolicies.Count > 0)
        {
            builder.AppendLine("using System.Threading.Tasks;");
            builder.AppendLine("using Microsoft.AspNetCore.Authentication;");
        }

        builder.AppendLine("using Microsoft.AspNetCore.Authorization;");
        if (anyOfPolicies.Count > 0)
        {
            builder.AppendLine("using Microsoft.AspNetCore.Http;");
        }

        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine();
        if (hasPolicies)
        {
            builder.AppendLine($"using {projectName}.Generated.Security;");
            builder.AppendLine();
        }

        builder.AppendLine($"namespace {projectName}.Generated.Security;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Extension methods for configuring API security policies.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine($"[GeneratedCode(\"{GeneratorInfo.Name}\", \"{GeneratorInfo.Version}\")]");
        builder.AppendLine("public static class SecurityServiceCollectionExtensions");
        builder.AppendLine("{");
        builder.AppendLine(4, "/// <summary>");
        builder.AppendLine(4, "/// Registers authorization policies for the API based on OpenAPI security requirements.");
        builder.AppendLine(4, "/// </summary>");
        builder.AppendLine(4, "/// <param name=\"services\">The service collection.</param>");
        builder.AppendLine(4, "/// <returns>The service collection for method chaining.</returns>");
        builder.AppendLine(4, "public static IServiceCollection AddApiSecurityPolicies(this IServiceCollection services)");
        builder.AppendLine(4, "{");

        // Generate method content
        var methodContent = GenerateMethodContent(policies, anyOfPolicies);
        builder.Append(methodContent);

        builder.AppendLine(4, "}");

        if (hasPolicies)
        {
            AppendHelpers(builder, anyOfPolicies.Count > 0);
        }

        builder.AppendLine("}");

        return builder.ToString();
    }

    /// <summary>
    /// Generates the method content for AddApiSecurityPolicies.
    /// </summary>
    private static string GenerateMethodContent(
        Dictionary<string, List<string>> policies,
        Dictionary<string, List<SecurityPoliciesExtractor.PolicyAlternative>> anyOfPolicies)
    {
        var builder = new StringBuilder();

        if (policies.Count == 0 && anyOfPolicies.Count == 0)
        {
            // Authenticated-only security: no policy to add, but UseAuthorization() still needs
            // the authorization services registered.
            builder.AppendLine(8, "services.AddAuthorization();");
            builder.AppendLine();
            builder.AppendLine(8, "return services;");

            return builder.ToString();
        }

        builder.AppendLine(8, "services.AddAuthorization(options =>");
        builder.AppendLine(8, "{");

        var sortedPolicies = policies
            .OrderBy(p => p.Key, StringComparer.Ordinal)
            .ToList();

        var isFirst = true;

        foreach (var policyKvp in sortedPolicies)
        {
            if (!isFirst)
            {
                builder.AppendLine();
            }

            isFirst = false;

            var policyName = policyKvp.Key;
            var scopes = policyKvp.Value;
            var constantName = SecurityPoliciesExtractor.GenerateConstantName(policyName);

            builder.AppendLine(12, $"options.AddPolicy(SecurityPolicies.{constantName}, policy =>");
            if (scopes.Count == 0)
            {
                // mutualTLS: no scope to find - the certificate scheme authenticated the caller
                builder.AppendLine(16, "policy.RequireAuthenticatedUser());");
            }
            else if (scopes.Count == 1)
            {
                builder.AppendLine(16, $"policy.RequireAssertion(context => {ScopeCondition(scopes[0])}));");
            }
            else
            {
                // Multiple scopes (AND logic): all required
                builder.AppendLine(16, "policy.RequireAssertion(context =>");
                var condition = string.Join(" &&\n                    ", scopes.Select(ScopeCondition));
                builder.AppendLine(20, $"{condition}));");
            }
        }

        // An operation whose alternatives differ (OR): the policy asks each scheme itself whether it
        // authenticated the caller, so a key holder gets in without the scopes a token would need.
        foreach (var anyOf in anyOfPolicies.OrderBy(p => p.Key, StringComparer.Ordinal))
        {
            if (!isFirst)
            {
                builder.AppendLine();
            }

            isFirst = false;

            builder.AppendLine(12, "// Any of the alternatives the specification lists (OR logic)");
            builder.AppendLine(12, $"options.AddPolicy(SecurityPolicies.{SecurityPoliciesExtractor.GenerateConstantName(anyOf.Key)}, policy =>");
            builder.AppendLine(16, "policy.RequireAssertion(async context =>");
            var alternatives = anyOf.Value.Select(a => a.Scopes.Count == 0
                ? $"await AuthenticatedWith(context, \"{CSharpLiteralHelper.EscapeString(a.AuthenticationScheme)}\")"
                : $"(await AuthenticatedWith(context, \"{CSharpLiteralHelper.EscapeString(a.AuthenticationScheme)}\") && {string.Join(" && ", a.Scopes.Select(ScopeCondition))})");
            builder.AppendLine(20, $"{string.Join(" ||\n                    ", alternatives)}));");
        }

        builder.AppendLine(8, "});");
        builder.AppendLine();
        builder.AppendLine(8, "return services;");

        return builder.ToString();
    }

    private static string ScopeCondition(string scope)
        => $"HasScope(context.User, \"{CSharpLiteralHelper.EscapeString(scope)}\")";

    /// <summary>
    /// The helpers the policies use: a scope as token handlers deliver it, and whether a scheme authenticated the caller.
    /// </summary>
    private static void AppendHelpers(
        StringBuilder builder,
        bool withAuthenticatedWith)
    {
        builder.AppendLine();
        builder.AppendLine(4, "/// <summary>");
        builder.AppendLine(4, "/// Whether the caller has a scope - as token handlers deliver scopes: one claim per scope, or one");
        builder.AppendLine(4, "/// space-separated claim, under <c>scope</c>, <c>scp</c>, or the claim type <c>scp</c> is mapped to.");
        builder.AppendLine(4, "/// </summary>");
        builder.AppendLine(4, "private static bool HasScope(");
        builder.AppendLine(8, "ClaimsPrincipal user,");
        builder.AppendLine(8, "string scope)");
        builder.AppendLine(4, "{");
        builder.AppendLine(8, "foreach (var claim in user.Claims)");
        builder.AppendLine(8, "{");
        builder.AppendLine(12, "if (claim.Type is \"scope\" or \"scp\" or \"http://schemas.microsoft.com/identity/claims/scope\" &&");
        builder.AppendLine(12, "    Array.IndexOf(claim.Value.Split(' '), scope) >= 0)");
        builder.AppendLine(12, "{");
        builder.AppendLine(16, "return true;");
        builder.AppendLine(12, "}");
        builder.AppendLine(8, "}");
        builder.AppendLine();
        builder.AppendLine(8, "return false;");
        builder.AppendLine(4, "}");

        if (!withAuthenticatedWith)
        {
            return;
        }

        builder.AppendLine();
        builder.AppendLine(4, "/// <summary>");
        builder.AppendLine(4, "/// Whether the authentication scheme authenticated the caller (a handler answers once per request).");
        builder.AppendLine(4, "/// </summary>");
        builder.AppendLine(4, "private static async Task<bool> AuthenticatedWith(");
        builder.AppendLine(8, "AuthorizationHandlerContext context,");
        builder.AppendLine(8, "string scheme)");
        builder.AppendLine(8, "=> context.Resource is HttpContext httpContext &&");
        builder.AppendLine(8, "   (await httpContext.AuthenticateAsync(scheme)).Succeeded;");
    }
}