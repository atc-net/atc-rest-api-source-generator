namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// The EndpointPerOperation client's support for a Server-Sent Events stream that lasts: what the last event said
/// (<c>ServerSentEventTracker</c>, behind a result's <c>EventName</c> and <c>Retry</c>), and
/// <c>ServerSentEventResume.ReadAsync</c>, which an operation that declares <c>Last-Event-ID</c> reads its items across
/// reconnects with (<c>ReadResumingAsync</c>): it sends the last id read, waits the server's <c>retry:</c> after the
/// stream ends and backs off while the server is away, until the server answers 204 or a 4xx.
/// </summary>
public static class ServerSentEventResumeExtractor
{
    /// <summary>
    /// Whether the document has an operation whose response is a Server-Sent Events stream.
    /// </summary>
    /// <param name="openApiDoc">The specification.</param>
    /// <returns>True when the support types are needed.</returns>
    public static bool IsNeeded(OpenApiDocument openApiDoc)
        => openApiDoc is not null &&
           openApiDoc
               .GetAllOperations()
               .Any(o => o.Operation.IsStreamingResponse() && o.Operation.GetStreamingFraming() == StreamingFraming.ServerSentEvents);

    /// <summary>
    /// The file content.
    /// </summary>
    /// <param name="projectName">The project name (root namespace).</param>
    /// <returns>The source.</returns>
    public static string Generate(string projectName)
        => $$"""
