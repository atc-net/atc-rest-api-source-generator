                 /// </summary>
                 /// <typeparam name="T">The item.</typeparam>
                 /// <typeparam name="TResult">The operation's result.</typeparam>
                 /// <param name="call">Calls the operation with a Last-Event-ID.</param>
                 /// <param name="lastEventId">The id to continue after, or null to start.</param>
                 /// <param name="policy">How to reconnect; the defaults when null.</param>
                 /// <param name="cancellationToken">Ends the reading.</param>
                 /// <returns>The items.</returns>
                 public static async IAsyncEnumerable<T?> ReadAsync<T, TResult>(
                     Func<string?, CancellationToken, Task<TResult>> call,
                     string? lastEventId,
                     ServerSentEventReconnectPolicy? policy,
                     [EnumeratorCancellation] CancellationToken cancellationToken = default)
                     where TResult : StreamingEndpointResponse<T>, IServerSentEventResult
                 {
                     if (call is null)
                     {
                         throw new ArgumentNullException(nameof(call));
                     }

                     policy ??= new ServerSentEventReconnectPolicy();
                     var failures = 0;
                     TimeSpan? retry = null;
                     while (true)
                     {
                         cancellationToken.ThrowIfCancellationRequested();

                         TResult? result = null;
                         Exception? error = null;
                         var read = false;
                         try
                         {
                             result = await call(lastEventId, cancellationToken).ConfigureAwait(false);
                         }
                         catch (Exception exception) when (IsBrokenConnection(exception, cancellationToken))
                         {
                             error = exception;
                         }

                         if (result is not null)
                         {
                             try
                             {
                                 var status = (int)result.StatusCode;
                                 if (status == 204 || (status is >= 400 and < 500 && status != 408 && status != 429))
                                 {
                                     yield break;
                                 }

