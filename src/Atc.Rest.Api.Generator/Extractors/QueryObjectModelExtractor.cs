namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// The <c>TryParse</c> of a model that is an object in the query (see <see cref="QueryObjectHelper"/>): it reads the
/// value the wire-binding step collected from the object's keys - <c>property=value</c> after the item separator,
/// each, an enum by its member name - and builds the model through its constructor. The framework then binds the
/// parameter as any query parameter, under RDG as under <c>RequestDelegateFactory</c>.
/// </summary>
public static class QueryObjectModelExtractor
{
    private const string ItemSeparator = "\\u001F";

    private static readonly HashSet<string> ParsableTypes = new(StringComparer.Ordinal)
    {
        "int", "long", "short", "byte", "sbyte", "uint", "ulong", "ushort", "decimal", "double", "float", "char",
        "Guid", "DateTime", "DateTimeOffset", "DateOnly", "TimeOnly", "TimeSpan", "Half", "Int128", "UInt128",
    };

    private static readonly HashSet<string> TextTypes = new(StringComparer.Ordinal)
    {
        "string", "object",
    };

    /// <summary>
    /// The partial of the model's record with its <c>TryParse</c>.
    /// </summary>
    /// <param name="record">The model's record, as generated.</param>
    /// <param name="queryObject">An object in the query the model is (its properties' wire names).</param>
    /// <param name="namespaceName">The model's namespace.</param>
    /// <param name="registry">The registry of the generation: an extensible enum property is parsed by its own TryParse.</param>
    /// <returns>The C# source.</returns>
    public static string Generate(
        RecordParameters record,
        OpenApiParameterExtensions.QueryObject queryObject,
        string namespaceName,
        TypeConflictRegistry? registry = null)
    {
        if (record is null)
        {
            throw new ArgumentNullException(nameof(record));
        }

        if (queryObject is null)
        {
            throw new ArgumentNullException(nameof(queryObject));
        }

        var typeName = record.Name.Split(' ')[0];
        var parameters = record.Parameters ?? [];
        var locals = new List<(ParameterBaseParameters Parameter, string Local, string? WireName)>();
        var extensibleEnums = new HashSet<string>(StringComparer.Ordinal);
        for (var i = 0; i < parameters.Count; i++)
        {
            var parameter = parameters[i];
            var property = queryObject.Properties
                .FirstOrDefault(p => string.Equals(Normalize(p.WireName), Normalize(parameter.Name), StringComparison.Ordinal));
            locals.Add((parameter, $"value{i.ToString(CultureInfo.InvariantCulture)}", property?.WireName));
            if (property is not null && ExtensibleEnumHelper.IsExtensibleEnum(property.Schema, registry))
            {
                extensibleEnums.Add(property.WireName);
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();
        sb.AppendLine($"public partial record {typeName}");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Reads the model from the query: the value the wire-binding step collected from its keys");
        sb.AppendLine("    /// (<c>property=value</c> after the item separator, each). False for a value it cannot read.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine($"    public static bool TryParse(string? value, [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out {typeName}? result)");
        sb.AppendLine("    {");
        sb.AppendLine("        result = null;");
        sb.AppendLine("        if (string.IsNullOrEmpty(value))");
        sb.AppendLine("        {");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine();
        foreach (var (parameter, local, _) in locals)
        {
            sb.AppendLine($"        {Simple(parameter)}? {local} = null;");
        }

        sb.AppendLine($"        foreach (var pair in value.Split('{ItemSeparator}', global::System.StringSplitOptions.RemoveEmptyEntries))");
        sb.AppendLine("        {");
        sb.AppendLine("            var separator = pair.IndexOf('=');");
        sb.AppendLine("            if (separator < 0)");
        sb.AppendLine("            {");
        sb.AppendLine("                return false;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            var text = pair.Substring(separator + 1);");
        sb.AppendLine("            switch (pair.Substring(0, separator))");
        sb.AppendLine("            {");
        foreach (var (parameter, local, wireName) in locals.Where(l => l.WireName is not null))
        {
            sb.AppendLine($"                case {CSharpLiteralHelper.ToStringLiteral(wireName!)}:");
            var parsed = local + "Parsed";
            var parse = ParseExpression(Simple(parameter), parsed, extensibleEnums.Contains(wireName!));
            if (parse is null)
            {
                sb.AppendLine($"                    {local} = text;");
            }
            else
            {
                sb.AppendLine($"                    if (!{parse})");
                sb.AppendLine("                    {");
                sb.AppendLine("                        return false;");
                sb.AppendLine("                    }");
                sb.AppendLine();
                sb.AppendLine($"                    {local} = {parsed};");
            }

            sb.AppendLine("                    break;");
        }

        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        result = new {typeName}(");
        for (var i = 0; i < locals.Count; i++)
        {
            var (parameter, local, _) = locals[i];
            sb.Append($"            {Argument(parameter, local)}");
            sb.AppendLine(i < locals.Count - 1 ? "," : ");");
        }

        if (locals.Count == 0)
        {
            sb.AppendLine("            );");
        }

        sb.AppendLine("        return true;");
        sb.AppendLine("    }");

        // An extensible enum is called through a type argument: in the record, its name is also the property's
        if (extensibleEnums.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("    // An extensible enum reads any text (IParsable)");
            sb.AppendLine("    private static bool TryParseExtensible<T>(string text, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out T value)");
            sb.AppendLine("        where T : global::System.IParsable<T>");
            sb.AppendLine("        => T.TryParse(text, global::System.Globalization.CultureInfo.InvariantCulture, out value);");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    // The property's type without '?' (the local is its nullable type)
    private static string Simple(ParameterBaseParameters parameter)
        => parameter.TypeName.TrimEnd('?');

    // The call that parses 'text' into 'parsed', or null for a type the text is; an extensible enum has a TryParse of
    // its own (it takes any text), a C# enum is read by its member name
    private static string? ParseExpression(
        string type,
        string parsed,
        bool extensibleEnum)
    {
        var simple = type.Replace("global::", string.Empty);
        simple = simple.StartsWith("System.", StringComparison.Ordinal) ? simple.Substring("System.".Length) : simple;
        return simple switch
        {
            _ when TextTypes.Contains(simple) => null,
            "bool" or "Boolean" => $"bool.TryParse(text, out var {parsed})",
            "Uri" => $"global::System.Uri.TryCreate(text, global::System.UriKind.RelativeOrAbsolute, out var {parsed})",
            _ when extensibleEnum => $"TryParseExtensible<{type}>(text, out var {parsed})",
            _ when ParsableTypes.Contains(simple) => $"{type}.TryParse(text, global::System.Globalization.CultureInfo.InvariantCulture, out var {parsed})",
            _ => $"global::System.Enum.TryParse<{type}>(text, ignoreCase: false, out var {parsed})",
        };
    }

    // The constructor argument: the value read, its default when absent, or the type's default (a required value the
    // wire-binding step already answered as missing)
    private static string Argument(
        ParameterBaseParameters parameter,
        string local)
    {
        if (parameter.DefaultValue is { } defaultValue && !string.Equals(defaultValue, "null", StringComparison.Ordinal))
        {
            var declaration = new StringBuilder();
            declaration.AppendTypeAndName(0, parameter.GenericTypeName, parameter.TypeName, isNullableType: false, parameter.Name, defaultValue);
            var text = declaration.ToString();
            return $"{local} ?? {text.Substring(text.IndexOf(" = ", StringComparison.Ordinal) + 3)}";
        }

        if (parameter.IsNullableType || parameter.TypeName.EndsWith("?", StringComparison.Ordinal))
        {
            return local;
        }

        return IsReference(Simple(parameter))
            ? $"{local}!"
            : $"{local}.GetValueOrDefault()";
    }

    private static bool IsReference(string type)
    {
        var simple = type.Replace("global::", string.Empty);
        simple = simple.StartsWith("System.", StringComparison.Ordinal) ? simple.Substring("System.".Length) : simple;
        return TextTypes.Contains(simple) || simple == "Uri";
    }

    // "perPage", "PerPage", "per_page" alike
    private static string Normalize(string name)
        => new(name.Where(char.IsLetterOrDigit).Select(char.ToLowerInvariant).ToArray());
}