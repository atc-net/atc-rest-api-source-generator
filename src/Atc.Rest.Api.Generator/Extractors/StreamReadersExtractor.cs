namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// Emits the generated <c>Streaming/StreamReaders.cs</c> helper that the C# clients use to read
/// OpenAPI 3.2 wire-framed streaming responses: Server-Sent Events (<c>text/event-stream</c>),
/// JSON Lines (<c>application/jsonl</c>), JSON Text Sequence (<c>application/json-seq</c>) and
/// multipart/mixed (<c>multipart/mixed</c>). The helper is emitted once per client (typed or
/// per-operation) only when the client has an operation that actually references it; the legacy
/// JSON-array framing reads via the legacy path and does not use it.
/// </summary>
public static class StreamReadersExtractor
{
    /// <summary>
    /// Determines whether the document declares any streaming operation: each reads through the emitted
    /// <c>StreamReaders</c> helper, whatever its framing - a JSON array, Server-Sent Events
    /// (<c>text/event-stream</c>), JSON Lines (<c>application/jsonl</c>), JSON Text Sequence
    /// (<c>application/json-seq</c>) or multipart/mixed.
    /// </summary>
    /// <param name="openApiDoc">The OpenAPI document.</param>
    /// <returns>True when at least one operation requires the StreamReaders helper.</returns>
    public static bool DocumentRequiresStreamReaders(OpenApiDocument openApiDoc)
    {
        if (openApiDoc?.Paths is null)
        {
            return false;
        }

        foreach (var path in openApiDoc.Paths)
        {
            if (path.Value?.Operations is null)
            {
                continue;
            }

            foreach (var operation in path.Value.Operations)
            {
                if (operation.Value.IsStreamingResponse())
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Generates the source content for the <c>Streaming/StreamReaders.cs</c> helper.
    /// The namespace is the client's generated root suffixed with <c>.Streaming</c>.
    /// </summary>
    /// <param name="projectName">The generated project name (e.g. the client root namespace prefix).</param>
    /// <returns>The full file content for the StreamReaders helper.</returns>
    public static string GenerateContent(string projectName)
        => TemplateText.Lines(
        [
            $$"""
            // <auto-generated />
            #nullable enable
            using System;
            using System.CodeDom.Compiler;
            using System.Collections.Generic;
            using System.IO;
            using System.Runtime.CompilerServices;
            """,

            // Encoding.UTF8 / StreamReader / StringBuilder for the JSON Lines (per-op) and
            // multipart/mixed (both variants) readers.
            $$"""
            using System.Text;
            using System.Text.Json;
            using System.Threading;
            using System.Threading.Tasks;

            namespace {{projectName}}.Generated.Streaming;

            [GeneratedCode("Atc.Rest.Api.SourceGenerator", "2.1.1")]
            internal static class StreamReaders
            {
                /// <summary>
                /// The longest record (a JSON Text Sequence record, a multipart part, a Server-Sent Event) or line (JSON Lines,
                /// a multipart header) a reader takes, in bytes or characters: a longer one is an InvalidDataException, not a
                /// buffer that grows until the process runs out of memory.
                /// Default: 16 MB.
                /// </summary>
                public static int MaxRecordLength { get; set; } = 16 * 1024 * 1024;

            """,

            // A JSON array (application/json), one element at a time. A body of nothing but whitespace - a 204, a 200
            // without content - is no items; the serializer alone would call that a broken array.
            $$"""
                public static async IAsyncEnumerable<T?> ReadJsonArrayAsync<T>(
                    Stream stream,
                    JsonSerializerOptions options,
                    [EnumeratorCancellation] CancellationToken cancellationToken)
                {
                    var first = new byte[1];
                    int read;
                    do
                    {
                        read = await stream.ReadAsync(first, cancellationToken).ConfigureAwait(false);
                    }
                    while (read == 1 && JsonBalance.IsWhitespace((char)first[0]));

                    if (read == 0)
                    {
                        yield break;
                    }

                    await foreach (var item in JsonSerializer.DeserializeAsyncEnumerable(new ElementLimitedStream(new PrefixedStream(first[0], stream)), options.TypeInfo<T>(), cancellationToken).ConfigureAwait(false))
                    {
                        yield return item;
                    }
                }

            """,

            // Server-Sent Events (text/event-stream), parsed here rather than by System.Net.ServerSentEvents: its
            // SseParser reports the event after an event without data under that event's name, and an item must not be
            // taken for a heartbeat. The item event is the unnamed one (or "message", the same by the standard) and the
            // ones the operation names with x-sse-item-events; any other named event - a heartbeat, a control frame - is
            // read past, as is a comment and an event without data.
            $$"""
                public static IAsyncEnumerable<T?> ReadServerSentEventsAsync<T>(
                    Stream stream,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                    => ReadServerSentEventsOfAsync<T>(stream, options, Array.Empty<string>(), cancellationToken);

                /// <summary>
                /// The items of an event stream whose items come in named events as well (x-sse-item-events): the unnamed
                /// event and the events named in itemEvents are items, every other named event is read past.
                /// </summary>
                public static async IAsyncEnumerable<T?> ReadServerSentEventsOfAsync<T>(
                    Stream stream,
                    JsonSerializerOptions options,
                    string[] itemEvents,
                    [EnumeratorCancellation] CancellationToken cancellationToken)
                {
                    using var reader = new StreamReader(new LineLimitedStream(stream, untilBlankLine: true), Encoding.UTF8, detectEncodingFromByteOrderMarks: false, bufferSize: 1024, leaveOpen: true);
                    string? eventType = null;
                    StringBuilder? data = null;
                    string? line;
                    while ((line = await reader.ReadLineAsync(cancellationToken).ConfigureAwait(false)) is not null)
                    {
                        if (line.Length == 0)
                        {
                            // The blank line that ends an event: the name is forgotten with it
                            var isItem = data is not null && (eventType is null || string.Equals(eventType, "message", StringComparison.Ordinal) || Array.IndexOf(itemEvents, eventType) >= 0);
                            var text = isItem ? data!.ToString() : string.Empty;
                            eventType = null;
                            data = null;
                            if (!string.IsNullOrWhiteSpace(text))
                            {
                                yield return JsonSerializer.Deserialize(text, options.TypeInfo<T>());
                            }

                            continue;
                        }

                        if (line[0] == ':')
                        {
                            continue;
                        }

                        var colon = line.IndexOf(':');
                        var field = colon < 0 ? line : line.Substring(0, colon);
                        var value = colon < 0 ? string.Empty : line.Substring(colon + 1);
                        if (value.Length > 0 && value[0] == ' ')
                        {
                            value = value.Substring(1);
                        }

                        if (string.Equals(field, "data", StringComparison.Ordinal))
                        {
                            data = data is null ? new StringBuilder(value) : data.Append('\n').Append(value);
                        }
                        else if (string.Equals(field, "event", StringComparison.Ordinal))
                        {
                            // An event field without a value names no event
                            eventType = value.Length == 0 ? null : value;
                        }
                    }
                }

            """,

            // JSON Lines / NDJSON (application/jsonl): newline-separated top-level JSON values.
            // Typed client has its configured JsonSerializerOptions in scope, so use the efficient
            // top-level-values overload (newline is JSON whitespace, so '\n'-separated values parse
            // natively without a per-line StreamReader).
            $$"""
                public static IAsyncEnumerable<T?> ReadJsonLinesAsync<T>(
                    Stream stream,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                    => JsonSerializer.DeserializeAsyncEnumerable(new LineLimitedStream(stream), options.TypeInfo<T>(), topLevelValues: true, cancellationToken);

            """,

            // The deserialize call differs only by variant: typed uses JsonSerializerOptions, per-op
            // uses the DI-configured IContractSerializer (both accept a UTF-8 byte[] record).
            // JSON Text Sequence, RFC 7464 (application/json-seq): each record is RS(0x1E) <json> LF.
            // RS is the delimiter PRECISELY so a record's JSON may contain embedded LFs (e.g. a
            // pretty-printed record from a third-party producer), so split on the RS byte — NOT on LF.
            // A raw 0x1E can never occur inside a JSON value (control chars are escaped), so the split
            // is unambiguous; any embedded/trailing LF is harmless JSON whitespace to the deserializer.
            // Read bytes truly-async (no thread-blocking sync I/O) and accumulate each record into a
            // MemoryStream — iterator-safe (no Span local crosses a yield).
            $$"""
                public static async IAsyncEnumerable<T?> ReadJsonSequenceAsync<T>(
                    Stream stream,
                    JsonSerializerOptions options,
                    [EnumeratorCancellation] CancellationToken cancellationToken)
                {
                    var buffer = new byte[4096];
                    using var record = new MemoryStream();
                    var balance = new JsonBalance();
                    int read;
                    while ((read = await stream.ReadAsync(buffer, cancellationToken).ConfigureAwait(false)) > 0)
                    {
                        for (var i = 0; i < read; i++)
                        {
                            var value = buffer[i];
                            if (value == 0x1E)
                            {
                                if (record.Length > 0)
                                {
                                    yield return JsonSerializer.Deserialize(record.ToArray(), options.TypeInfo<T>());
                                    record.SetLength(0);
                                    balance.Reset();
                                }
                            }
                            else if (value == (byte)'\n' && balance.IsComplete)
                            {
                                // The LF that ends a record: yielded now, not at the next record's separator - a server that fails
                                // after this record never sends one (a pretty-printed record is complete only once it is balanced)
                                yield return JsonSerializer.Deserialize(record.ToArray(), options.TypeInfo<T>());
                                record.SetLength(0);
                                balance.Reset();
                            }
                            else if (record.Length == 0 && JsonBalance.IsWhitespace((char)value))
                            {
                                // Whitespace between two records (a second line feed, an empty record) is no record
                            }
                            else
                            {
                                record.WriteByte(value);
                                balance.Add((char)value);
                                if (record.Length > MaxRecordLength)
                                {
                                    throw new InvalidDataException($"A JSON Text Sequence record is longer than {MaxRecordLength} bytes.");
                                }
                            }
                        }
                    }

                    if (record.Length > 0)
                    {
                        yield return JsonSerializer.Deserialize(record.ToArray(), options.TypeInfo<T>());
                    }
                }

            """,

            // The multipart deserialize call differs only by variant — the typed reader uses the
            // JsonSerializerOptions and the per-op reader uses the DI-configured IContractSerializer.
            // Both take the accumulated body string.
            // multipart/mixed: parts are delimited by `--<boundary>` lines, each part has headers up to
            // a blank line, then the JSON body; the stream ends at `--<boundary>--`. Accumulate body
            // lines (so multi-line / pretty-printed bodies reconstitute into one valid JSON document —
            // interior LFs are insignificant JSON whitespace, and the boundary token cannot appear at
            // the start of a JSON body line). Read truly-async via StreamReader.ReadLineAsync.
            $$"""
                public static async IAsyncEnumerable<T?> ReadMultipartMixedAsync<T>(
                    Stream stream,
                    string boundary,
                    JsonSerializerOptions options,
                    [EnumeratorCancellation] CancellationToken cancellationToken)
                {
                    var delimiter = "--" + boundary;
                    using var reader = new StreamReader(new LineLimitedStream(stream), Encoding.UTF8, detectEncodingFromByteOrderMarks: false, bufferSize: 1024, leaveOpen: true);
                    var inPart = false;
                    var inHeaders = false;
                    var body = new StringBuilder();
                    var bodyBytes = 0L;
                    var balance = new JsonBalance();
                    string? line;
                    while ((line = await reader.ReadLineAsync(cancellationToken).ConfigureAwait(false)) is not null)
                    {
                        var boundaryLine = BoundaryLine(line, delimiter);
                        if (boundaryLine != 0)
                        {
                            if (inPart && body.Length > 0)
                            {
                                yield return JsonSerializer.Deserialize(body.ToString(), options.TypeInfo<T>());
                                body.Clear();
                            }

                            bodyBytes = 0;
                            balance.Reset();
                            if (boundaryLine == 2)
                            {
                                yield break;
                            }

                            inPart = true;
                            inHeaders = true;
                            continue;
                        }

                        if (!inPart)
                        {
                            continue;
                        }

                        if (inHeaders)
                        {
                            if (line.Length == 0)
                            {
                                inHeaders = false;
                            }

                            continue;
                        }

                        body.Append(line);
                        balance.Add(line);
                        bodyBytes += Encoding.UTF8.GetByteCount(line);
                        if (bodyBytes > MaxRecordLength)
                        {
                            throw new InvalidDataException($"A multipart part is longer than {MaxRecordLength} bytes.");
                        }

                        // A body that is complete JSON is yielded now, not at the next boundary - a server that fails after
                        // this part never sends one
                        if (balance.IsComplete)
                        {
                            yield return JsonSerializer.Deserialize(body.ToString(), options.TypeInfo<T>());
                            body.Clear();
                            bodyBytes = 0;
                            balance.Reset();
                        }
                    }

                    if (inPart && body.Length > 0)
                    {
                        yield return JsonSerializer.Deserialize(body.ToString(), options.TypeInfo<T>());
                    }
                }

                /// <summary>
                /// A byte already read from a stream, and then the stream: what ReadJsonArrayAsync hands the serializer after
                /// it has looked for the first byte of the array. The stream read from is not this one's to close.
                /// </summary>
                private sealed class PrefixedStream : Stream
                {
                    private readonly byte first;
                    private readonly Stream rest;
                    private bool firstRead;

                    public PrefixedStream(byte first, Stream rest)
                    {
                        this.first = first;
                        this.rest = rest;
                    }

                    public override bool CanRead => true;

                    public override bool CanSeek => false;

                    public override bool CanWrite => false;

                    public override long Length => throw new NotSupportedException();

                    public override long Position
                    {
                        get => throw new NotSupportedException();
                        set => throw new NotSupportedException();
                    }

                    public override void Flush()
                    {
                    }

                    public override int Read(byte[] buffer, int offset, int count)
                    {
                        if (firstRead || count == 0)
                        {
                            return rest.Read(buffer, offset, count);
                        }

                        // With what follows it, so that the reader sees a byte order mark whole
                        firstRead = true;
                        buffer[offset] = first;
                        return 1 + (count > 1 ? rest.Read(buffer, offset + 1, count - 1) : 0);
                    }

                    public override async ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
                    {
                        if (firstRead || buffer.Length == 0)
                        {
                            return await rest.ReadAsync(buffer, cancellationToken).ConfigureAwait(false);
                        }

                        firstRead = true;
                        buffer.Span[0] = first;
                        return 1 + (buffer.Length > 1 ? await rest.ReadAsync(buffer.Slice(1), cancellationToken).ConfigureAwait(false) : 0);
                    }

                    public override Task<int> ReadAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken)
                        => ReadAsync(buffer.AsMemory(offset, count), cancellationToken).AsTask();

                    public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();

                    public override void SetLength(long value) => throw new NotSupportedException();

                    public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
                }

            """,

            // A boundary line is the delimiter, "--" after it on the last one, and nothing but spaces and tabs behind: a
            // line that only starts like the delimiter (another, longer boundary) is none
            $$"""
                // 0: no boundary line, 1: the boundary before a part, 2: the closing boundary
                private static int BoundaryLine(
                    string line,
                    string delimiter)
                {
                    if (!line.StartsWith(delimiter, StringComparison.Ordinal))
                    {
                        return 0;
                    }

                    var index = delimiter.Length;
                    var closing = string.CompareOrdinal(line, index, "--", 0, 2) == 0;
                    if (closing)
                    {
                        index += 2;
                    }

                    for (; index < line.Length; index++)
                    {
                        if (line[index] != ' ' && line[index] != '\t')
                        {
                            return 0;
                        }
                    }

                    return closing ? 2 : 1;
                }

            """,

            // Whether what was read so far is one JSON text: kept up as the characters arrive, so a record of many lines
            // is not read again at each of them. A UTF-8 byte may be given as a character - what counts here is ASCII
            $$"""
                /// <summary>
                /// Whether the characters given so far are one balanced JSON text: objects and arrays closed, no open string,
                /// something besides whitespace.
                /// </summary>
                private sealed class JsonBalance
                {
                    private int depth;
                    private bool inString;
                    private bool escaped;
                    private bool seen;

                    public bool IsComplete => seen && depth == 0 && !inString;

                    public static bool IsWhitespace(char ch)
                        => ch == ' ' || ch == '\t' || ch == '\r' || ch == '\n';

                    public void Reset()
                    {
                        depth = 0;
                        inString = false;
                        escaped = false;
                        seen = false;
                    }

                    public void Add(string text)
                    {
                        foreach (var ch in text)
                        {
                            Add(ch);
                        }
                    }

                    public void Add(char ch)
                    {
                        if (inString)
                        {
                            if (escaped) { escaped = false; } else if (ch == '\\') { escaped = true; } else if (ch == '"') { inString = false; }
                            return;
                        }

                        if (IsWhitespace(ch)) { return; }
                        seen = true;
                        if (ch == '"') { inString = true; } else if (ch == '{' || ch == '[') { depth++; } else if (ch == '}' || ch == ']') { depth--; }
                    }
                }

            """,

            // The line cap of the framings read line by line: counted where the bytes arrive, so no reader behind it
            // (a StreamReader, the SSE parser, the JSON reader) has buffered a line that never ends
            $$"""
                /// <summary>
                /// What a reader reads through when the framing is made of lines (JSON Lines, Server-Sent Events, multipart): a
                /// line longer than MaxRecordLength is an InvalidDataException before the reader behind it has buffered it. A line
                /// ends at LF, CR or CRLF. With untilBlankLine the count runs on to the blank line that ends a Server-Sent Event,
                /// so an event of many short lines is limited as well. The stream read from is not this one's to close.
                /// </summary>
                private sealed class LineLimitedStream : CountingStream
                {
                    private readonly bool untilBlankLine;
                    private long length;
                    private bool lineIsEmpty = true;
                    private bool afterCarriageReturn;

                    public LineLimitedStream(Stream inner, bool untilBlankLine = false)
                        : base(inner)
                    {
                        this.untilBlankLine = untilBlankLine;
                    }

                    protected override void Count(ReadOnlySpan<byte> bytes)
                    {
                        while (!bytes.IsEmpty)
                        {
                            var end = bytes.IndexOfAny((byte)'\n', (byte)'\r');
                            var taken = end < 0 ? bytes.Length : end;
                            if (taken > 0)
                            {
                                length += taken;
                                lineIsEmpty = false;
                                afterCarriageReturn = false;
                                if (length > MaxRecordLength)
                                {
                                    throw new InvalidDataException(untilBlankLine
                                        ? $"An event of the stream is longer than {MaxRecordLength} bytes."
                                        : $"A line of the stream is longer than {MaxRecordLength} bytes.");
                                }
                            }

                            if (end < 0)
                            {
                                return;
                            }

                            // The LF of a CRLF ends no line of its own
                            var isLineFeedOfPair = bytes[end] == (byte)'\n' && afterCarriageReturn;
                            afterCarriageReturn = bytes[end] == (byte)'\r';
                            if (!isLineFeedOfPair)
                            {
                                if (!untilBlankLine || lineIsEmpty)
                                {
                                    length = 0;
                                }

                                lineIsEmpty = true;
                            }

                            bytes = bytes.Slice(end + 1);
                        }
                    }
                }

            """,

            // The element cap of a JSON array: the serializer reads an element whole before it is handed out, so an element
            // that never ends would be buffered without end
            $$"""
                /// <summary>
                /// What the serializer reads a JSON array through: an element longer than MaxRecordLength is an
                /// InvalidDataException before the serializer has buffered it. An element ends at the comma (or the bracket)
                /// after it, outside a string. The stream read from is not this one's to close.
                /// </summary>
                private sealed class ElementLimitedStream : CountingStream
                {
                    private long length;
                    private int depth;
                    private bool inString;
                    private bool escaped;

                    public ElementLimitedStream(Stream inner)
                        : base(inner)
                    {
                    }

                    protected override void Count(ReadOnlySpan<byte> bytes)
                    {
                        foreach (var b in bytes)
                        {
                            length++;
                            if (inString)
                            {
                                if (escaped)
                                {
                                    escaped = false;
                                }
                                else if (b == (byte)'\\')
                                {
                                    escaped = true;
                                }
                                else if (b == (byte)'"')
                                {
                                    inString = false;
                                }
                            }
                            else if (b == (byte)'"')
                            {
                                inString = true;
                            }
                            else if (b is (byte)'{' or (byte)'[')
                            {
                                depth++;
                            }
                            else if (b is (byte)'}' or (byte)']')
                            {
                                depth--;
                            }

                            // Between two elements of the array (or at its end) a new element starts
                            if (!inString && depth <= 1 && b is (byte)',' or (byte)'[' or (byte)']')
                            {
                                length = 0;
                            }
                            else if (length > MaxRecordLength)
                            {
                                throw new InvalidDataException($"An element of the JSON array is longer than {MaxRecordLength} bytes.");
                            }
                        }
                    }
                }

            """,

            // What both caps share: a stream that counts what passes through it, before the reader behind it sees it
            $$"""
                /// <summary>
                /// A stream read through, its bytes counted as they arrive (see LineLimitedStream, ElementLimitedStream). The
                /// stream read from is not this one's to close.
                /// </summary>
                private abstract class CountingStream : Stream
                {
                    private readonly Stream inner;

                    protected CountingStream(Stream inner)
                        => this.inner = inner;

                    public override bool CanRead => true;

                    public override bool CanSeek => false;

                    public override bool CanWrite => false;

                    public override long Length => throw new NotSupportedException();

                    public override long Position
                    {
                        get => throw new NotSupportedException();
                        set => throw new NotSupportedException();
                    }

                    public override void Flush()
                    {
                    }

                    public override int Read(byte[] buffer, int offset, int count)
                    {
                        var read = inner.Read(buffer, offset, count);
                        Count(buffer.AsSpan(offset, read));
                        return read;
                    }

                    public override async ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
                    {
                        var read = await inner.ReadAsync(buffer, cancellationToken).ConfigureAwait(false);
                        Count(buffer.Span.Slice(0, read));
                        return read;
                    }

                    public override Task<int> ReadAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken)
                        => ReadAsync(buffer.AsMemory(offset, count), cancellationToken).AsTask();

                    public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();

                    public override void SetLength(long value) => throw new NotSupportedException();

                    public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();

                    protected abstract void Count(ReadOnlySpan<byte> bytes);
                }
            }
            """,
        ]);
}