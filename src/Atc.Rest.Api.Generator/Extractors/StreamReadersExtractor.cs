namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// Emits the generated <c>Streaming/StreamReaders.cs</c> helper that the C# clients use to read
/// OpenAPI 3.2 wire-framed streaming responses: Server-Sent Events (<c>text/event-stream</c>),
/// JSON Lines (<c>application/jsonl</c>), JSON Text Sequence (<c>application/json-seq</c>) and
/// multipart/mixed (<c>multipart/mixed</c>). The helper is emitted once per client (typed or
/// per-operation) only when the client has an operation that actually references it; the legacy
/// JSON-array framing reads via the legacy path and does not use it.
/// </summary>
public static class StreamReadersExtractor
{
    /// <summary>
    /// Determines whether the document declares any streaming operation that references the
    /// emitted <c>StreamReaders</c> helper. That is a Server-Sent Events (<c>text/event-stream</c>),
    /// JSON Lines (<c>application/jsonl</c>), JSON Text Sequence (<c>application/json-seq</c>) or
    /// multipart/mixed (<c>multipart/mixed</c>) operation; the legacy JSON-array framing reads via
    /// the legacy path and does not use it.
    /// </summary>
    /// <param name="openApiDoc">The OpenAPI document.</param>
    /// <returns>True when at least one operation requires the StreamReaders helper.</returns>
    public static bool DocumentRequiresStreamReaders(OpenApiDocument openApiDoc)
    {
        if (openApiDoc?.Paths is null)
        {
            return false;
        }

        foreach (var path in openApiDoc.Paths)
        {
            if (path.Value?.Operations is null)
            {
                continue;
            }

            foreach (var operation in path.Value.Operations)
            {
                // Emit the helper only when an operation actually references it: SSE, JSON Lines,
                // JSON Text Sequence and multipart/mixed. The legacy JSON-array framing still reads
                // via the DeserializeAsyncEnumerable path and never calls StreamReaders, so a
                // JsonArray-only spec must not ship an orphan helper.
                if (!operation.Value.IsStreamingResponse())
                {
                    continue;
                }

                var framing = operation.Value.GetStreamingFraming();
                if (framing is StreamingFraming.ServerSentEvents
                    or StreamingFraming.JsonLines
                    or StreamingFraming.JsonSequence
                    or StreamingFraming.MultipartMixed)
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Generates the source content for the <c>Streaming/StreamReaders.cs</c> helper.
    /// The namespace is the client's generated root suffixed with <c>.Streaming</c>.
    /// </summary>
    /// <param name="projectName">The generated project name (e.g. the client root namespace prefix).</param>
    /// <param name="perOperation">
    /// When <c>true</c>, emit the per-operation variant that deserializes each event via the
    /// DI-configured <c>IContractSerializer</c> (so the per-op client honors the same serialization
    /// the legacy <c>BuildStreamingEndpointResponseAsync</c> path uses). When <c>false</c> (typed
    /// client), the reader takes <c>JsonSerializerOptions</c> — the typed client already has its
    /// configured <c>jsonSerializerOptions</c> in scope. A generated client is entirely typed OR
    /// entirely per-operation, so only one variant is ever emitted into a given project.
    /// </param>
    /// <returns>The full file content for the StreamReaders helper.</returns>
    public static string GenerateContent(
        string projectName,
        bool perOperation = false)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.CodeDom.Compiler;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.IO;");
        sb.AppendLine("using System.Net.ServerSentEvents;");
        sb.AppendLine("using System.Runtime.CompilerServices;");

        // Encoding.UTF8 / StreamReader / StringBuilder for the JSON Lines (per-op) and
        // multipart/mixed (both variants) readers.
        sb.AppendLine("using System.Text;");
        if (!perOperation)
        {
            sb.AppendLine("using System.Text.Json;");
        }

        sb.AppendLine("using System.Threading;");
        if (perOperation)
        {
            sb.AppendLine("using Atc.Rest.Client.Serialization;");
        }

        sb.AppendLine();
        sb.AppendLine($"namespace {projectName}.Generated.Streaming;");
        sb.AppendLine();
        sb.AppendLine($"[GeneratedCode(\"{GeneratorInfo.Name}\", \"{GeneratorInfo.Version}\")]");
        sb.AppendLine("internal static class StreamReaders");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// The longest record (a JSON Text Sequence record, a multipart part) a reader buffers, in bytes or characters:");
        sb.AppendLine("    /// a longer one is an InvalidDataException, not a buffer that grows until the process runs out of memory.");
        sb.AppendLine("    /// Default: 16 MB.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static int MaxRecordLength { get; set; } = 16 * 1024 * 1024;");
        sb.AppendLine();
        sb.AppendLine("    public static async IAsyncEnumerable<T?> ReadServerSentEventsAsync<T>(");
        sb.AppendLine("        Stream stream,");
        if (perOperation)
        {
            sb.AppendLine("        IContractSerializer serializer,");
            sb.AppendLine("        [EnumeratorCancellation] CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            sb.AppendLine("        var parser = SseParser.Create(");
            sb.AppendLine("            stream,");
            sb.AppendLine("            (eventType, bytes) => ReadEvent(eventType, bytes, data => serializer.Deserialize<T>(data)));");
        }
        else
        {
            sb.AppendLine("        JsonSerializerOptions options,");
            sb.AppendLine("        [EnumeratorCancellation] CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            sb.AppendLine("        var parser = SseParser.Create(");
            sb.AppendLine("            stream,");
            sb.AppendLine("            (eventType, bytes) => ReadEvent(eventType, bytes, data => JsonSerializer.Deserialize<T>(data, options)));");
        }

        sb.AppendLine();
        sb.AppendLine("        await foreach (var item in parser.EnumerateAsync(cancellationToken))");
        sb.AppendLine("        {");
        sb.AppendLine("            if (item.Data.IsItem)");
        sb.AppendLine("            {");
        sb.AppendLine("                yield return item.Data.Value;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        // What an event stream carries besides the items: an event without data is no item; a named event whose data
        // is no item (a heartbeat, a control frame) is skipped; an unnamed event - the item event - must be one
        sb.AppendLine("    private static (bool IsItem, T? Value) ReadEvent<T>(");
        sb.AppendLine("        string eventType,");
        sb.AppendLine("        ReadOnlySpan<byte> data,");
        sb.AppendLine("        Func<byte[], T?> deserialize)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (data.Trim(\" \\t\\r\\n\"u8).IsEmpty)");
        sb.AppendLine("        {");
        sb.AppendLine("            return (false, default);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            return (true, deserialize(data.ToArray()));");
        sb.AppendLine("        }");
        sb.AppendLine("        catch (global::System.Text.Json.JsonException) when (!string.Equals(eventType, SseParser.EventTypeDefault, StringComparison.Ordinal))");
        sb.AppendLine("        {");
        sb.AppendLine("            return (false, default);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        // JSON Lines / NDJSON (application/jsonl): newline-separated top-level JSON values.
        if (perOperation)
        {
            // Per-operation client has no JsonSerializerOptions in scope and IContractSerializer
            // exposes no topLevelValues overload (its DeserializeAsyncEnumerable reads a JSON
            // array, not jsonl), so read the stream line-by-line and deserialize each non-empty
            // line via the DI-configured serializer — matching the SSE per-op serialization path.
            sb.AppendLine("    public static async IAsyncEnumerable<T?> ReadJsonLinesAsync<T>(");
            sb.AppendLine("        Stream stream,");
            sb.AppendLine("        IContractSerializer serializer,");
            sb.AppendLine("        [EnumeratorCancellation] CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            sb.AppendLine("        using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: false, bufferSize: 1024, leaveOpen: true);");
            sb.AppendLine("        string? line;");
            sb.AppendLine("        while ((line = await reader.ReadLineAsync(cancellationToken)) is not null)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (line.Length == 0)");
            sb.AppendLine("            {");
            sb.AppendLine("                continue;");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            yield return serializer.Deserialize<T>(line);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }
        else
        {
            // Typed client has its configured JsonSerializerOptions in scope, so use the efficient
            // top-level-values overload (newline is JSON whitespace, so '\n'-separated values parse
            // natively without a per-line StreamReader).
            sb.AppendLine("    public static IAsyncEnumerable<T?> ReadJsonLinesAsync<T>(");
            sb.AppendLine("        Stream stream,");
            sb.AppendLine("        JsonSerializerOptions options,");
            sb.AppendLine("        CancellationToken cancellationToken)");
            sb.AppendLine("        => JsonSerializer.DeserializeAsyncEnumerable<T>(stream, topLevelValues: true, options, cancellationToken);");
        }

        sb.AppendLine();

        // The deserialize call differs only by variant: typed uses JsonSerializerOptions, per-op
        // uses the DI-configured IContractSerializer (both accept a UTF-8 byte[] record).
        var deserializeRecord = perOperation
            ? "serializer.Deserialize<T>(record.ToArray())"
            : "JsonSerializer.Deserialize<T>(record.ToArray(), options)";

        // JSON Text Sequence, RFC 7464 (application/json-seq): each record is RS(0x1E) <json> LF.
        // RS is the delimiter PRECISELY so a record's JSON may contain embedded LFs (e.g. a
        // pretty-printed record from a third-party producer), so split on the RS byte — NOT on LF.
        // A raw 0x1E can never occur inside a JSON value (control chars are escaped), so the split
        // is unambiguous; any embedded/trailing LF is harmless JSON whitespace to the deserializer.
        // Read bytes truly-async (no thread-blocking sync I/O) and accumulate each record into a
        // MemoryStream — iterator-safe (no Span local crosses a yield).
        sb.AppendLine("    public static async IAsyncEnumerable<T?> ReadJsonSequenceAsync<T>(");
        sb.AppendLine("        Stream stream,");
        if (perOperation)
        {
            sb.AppendLine("        IContractSerializer serializer,");
        }
        else
        {
            sb.AppendLine("        JsonSerializerOptions options,");
        }

        sb.AppendLine("        [EnumeratorCancellation] CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        var buffer = new byte[4096];");
        sb.AppendLine("        using var record = new MemoryStream();");
        sb.AppendLine("        int read;");
        sb.AppendLine("        while ((read = await stream.ReadAsync(buffer, cancellationToken)) > 0)");
        sb.AppendLine("        {");
        sb.AppendLine("            for (var i = 0; i < read; i++)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (buffer[i] == 0x1E)");
        sb.AppendLine("                {");
        sb.AppendLine("                    if (record.Length > 0)");
        sb.AppendLine("                    {");
        sb.AppendLine($"                        yield return {deserializeRecord};");
        sb.AppendLine("                        record.SetLength(0);");
        sb.AppendLine("                    }");
        sb.AppendLine("                }");
        sb.AppendLine("                else if (buffer[i] == (byte)'\\n' && record.Length > 0 && IsCompleteJson(Encoding.UTF8.GetString(record.GetBuffer(), 0, (int)record.Length)))");
        sb.AppendLine("                {");
        sb.AppendLine("                    // The LF that ends a record: yielded now, not at the next record's separator - a server that fails");
        sb.AppendLine("                    // after this record never sends one (a pretty-printed record is complete only once it is balanced)");
        sb.AppendLine($"                    yield return {deserializeRecord};");
        sb.AppendLine("                    record.SetLength(0);");
        sb.AppendLine("                }");
        sb.AppendLine("                else");
        sb.AppendLine("                {");
        sb.AppendLine("                    record.WriteByte(buffer[i]);");
        sb.AppendLine("                    if (record.Length > MaxRecordLength)");
        sb.AppendLine("                    {");
        sb.AppendLine("                        throw new InvalidDataException($\"A JSON Text Sequence record is longer than {MaxRecordLength} bytes.\");");
        sb.AppendLine("                    }");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        if (record.Length > 0)");
        sb.AppendLine("        {");
        sb.AppendLine($"            yield return {deserializeRecord};");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        // The multipart deserialize call differs only by variant — the typed reader uses the
        // JsonSerializerOptions and the per-op reader uses the DI-configured IContractSerializer.
        // Both take the accumulated body string.
        var deserializeBody = perOperation
            ? "serializer.Deserialize<T>(body.ToString())"
            : "JsonSerializer.Deserialize<T>(body.ToString(), options)";

        // multipart/mixed: parts are delimited by `--<boundary>` lines, each part has headers up to
        // a blank line, then the JSON body; the stream ends at `--<boundary>--`. Accumulate body
        // lines (so multi-line / pretty-printed bodies reconstitute into one valid JSON document —
        // interior LFs are insignificant JSON whitespace, and the boundary token cannot appear at
        // the start of a JSON body line). Read truly-async via StreamReader.ReadLineAsync.
        sb.AppendLine("    public static async IAsyncEnumerable<T?> ReadMultipartMixedAsync<T>(");
        sb.AppendLine("        Stream stream,");
        sb.AppendLine("        string boundary,");
        if (perOperation)
        {
            sb.AppendLine("        IContractSerializer serializer,");
        }
        else
        {
            sb.AppendLine("        JsonSerializerOptions options,");
        }

        sb.AppendLine("        [EnumeratorCancellation] CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        var delimiter = \"--\" + boundary;");
        sb.AppendLine("        using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: false, bufferSize: 1024, leaveOpen: true);");
        sb.AppendLine("        var inPart = false;");
        sb.AppendLine("        var inHeaders = false;");
        sb.AppendLine("        var body = new StringBuilder();");
        sb.AppendLine("        string? line;");
        sb.AppendLine("        while ((line = await reader.ReadLineAsync(cancellationToken)) is not null)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (line.StartsWith(delimiter, StringComparison.Ordinal))");
        sb.AppendLine("            {");
        sb.AppendLine("                if (inPart && body.Length > 0)");
        sb.AppendLine("                {");
        sb.AppendLine($"                    yield return {deserializeBody};");
        sb.AppendLine("                    body.Clear();");
        sb.AppendLine("                }");
        sb.AppendLine();
