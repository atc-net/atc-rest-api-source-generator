namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// Emits the generated <c>Streaming/StreamReaders.cs</c> helper that the C# clients use to
/// read OpenAPI 3.2 wire-framed streaming responses (e.g. Server-Sent Events). The helper is
/// emitted once per client (typed or per-operation) only when the client has an operation that
/// actually references it — currently a <see cref="StreamingFraming.ServerSentEvents"/> operation.
/// </summary>
public static class StreamReadersExtractor
{
    /// <summary>
    /// Determines whether the document declares any streaming operation that references the
    /// emitted <c>StreamReaders</c> helper. Today that is a Server-Sent Events operation
    /// (<c>text/event-stream</c>) or a JSON Lines operation (<c>application/jsonl</c>); the
    /// remaining framings read via the legacy path and do not use it.
    /// </summary>
    /// <param name="openApiDoc">The OpenAPI document.</param>
    /// <returns>True when at least one operation requires the StreamReaders helper.</returns>
    public static bool DocumentRequiresStreamReaders(OpenApiDocument openApiDoc)
    {
        if (openApiDoc?.Paths == null)
        {
            return false;
        }

        foreach (var path in openApiDoc.Paths)
        {
            if (path.Value?.Operations == null)
            {
                continue;
            }

            foreach (var operation in path.Value.Operations)
            {
                // Emit the helper only when an operation actually references it. Today that is
                // Server-Sent Events and JSON Lines; the remaining framings (JsonArray, ...) still
                // read via the legacy DeserializeAsyncEnumerable path and never call StreamReaders,
                // so a legacy-only spec must not ship an orphan helper. Tasks that add reader
                // helpers for the remaining framings widen this gate as they start using StreamReaders.
                if (!operation.Value.IsStreamingResponse())
                {
                    continue;
                }

                var framing = operation.Value.GetStreamingFraming();
                if (framing is StreamingFraming.ServerSentEvents or StreamingFraming.JsonLines)
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Generates the source content for the <c>Streaming/StreamReaders.cs</c> helper.
    /// The namespace is the client's generated root suffixed with <c>.Streaming</c>.
    /// </summary>
    /// <param name="projectName">The generated project name (e.g. the client root namespace prefix).</param>
    /// <param name="perOperation">
    /// When <c>true</c>, emit the per-operation variant that deserializes each event via the
    /// DI-configured <c>IContractSerializer</c> (so the per-op client honors the same serialization
    /// the legacy <c>BuildStreamingEndpointResponseAsync</c> path uses). When <c>false</c> (typed
    /// client), the reader takes <c>JsonSerializerOptions</c> — the typed client already has its
    /// configured <c>jsonSerializerOptions</c> in scope. A generated client is entirely typed OR
    /// entirely per-operation, so only one variant is ever emitted into a given project.
    /// </param>
    /// <returns>The full file content for the StreamReaders helper.</returns>
    public static string GenerateContent(
        string projectName,
        bool perOperation = false)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.CodeDom.Compiler;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.IO;");
        sb.AppendLine("using System.Net.ServerSentEvents;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        if (!perOperation)
        {
            sb.AppendLine("using System.Text.Json;");
        }

        if (perOperation)
        {
            sb.AppendLine("using System.Text;");
        }

        sb.AppendLine("using System.Threading;");
        if (perOperation)
        {
            sb.AppendLine("using Atc.Rest.Client.Serialization;");
        }

        sb.AppendLine();
        sb.AppendLine($"namespace {projectName}.Generated.Streaming;");
        sb.AppendLine();
        sb.AppendLine($"[GeneratedCode(\"{GeneratorInfo.Name}\", \"{GeneratorInfo.Version}\")]");
        sb.AppendLine("internal static class StreamReaders");
        sb.AppendLine("{");
        sb.AppendLine("    public static async IAsyncEnumerable<T?> ReadServerSentEventsAsync<T>(");
        sb.AppendLine("        Stream stream,");
        if (perOperation)
        {
            sb.AppendLine("        IContractSerializer serializer,");
            sb.AppendLine("        [EnumeratorCancellation] CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            sb.AppendLine("        var parser = SseParser.Create(");
            sb.AppendLine("            stream,");
            sb.AppendLine("            (eventType, bytes) => serializer.Deserialize<T>(bytes.ToArray()));");
        }
        else
        {
            sb.AppendLine("        JsonSerializerOptions options,");
            sb.AppendLine("        [EnumeratorCancellation] CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            sb.AppendLine("        var parser = SseParser.Create(");
            sb.AppendLine("            stream,");
            sb.AppendLine("            (eventType, bytes) => JsonSerializer.Deserialize<T>(bytes, options));");
        }

        sb.AppendLine();
        sb.AppendLine("        await foreach (var item in parser.EnumerateAsync(cancellationToken))");
        sb.AppendLine("        {");
        sb.AppendLine("            yield return item.Data;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        // JSON Lines / NDJSON (application/jsonl): newline-separated top-level JSON values.
        if (perOperation)
        {
            // Per-operation client has no JsonSerializerOptions in scope and IContractSerializer
            // exposes no topLevelValues overload (its DeserializeAsyncEnumerable reads a JSON
            // array, not jsonl), so read the stream line-by-line and deserialize each non-empty
            // line via the DI-configured serializer — matching the SSE per-op serialization path.
            sb.AppendLine("    public static async IAsyncEnumerable<T?> ReadJsonLinesAsync<T>(");
            sb.AppendLine("        Stream stream,");
            sb.AppendLine("        IContractSerializer serializer,");
            sb.AppendLine("        [EnumeratorCancellation] CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            sb.AppendLine("        using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: false, bufferSize: 1024, leaveOpen: true);");
            sb.AppendLine("        string? line;");
            sb.AppendLine("        while ((line = await reader.ReadLineAsync(cancellationToken)) != null)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (line.Length == 0)");
            sb.AppendLine("            {");
            sb.AppendLine("                continue;");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            yield return serializer.Deserialize<T>(line);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }
        else
        {
            // Typed client has its configured JsonSerializerOptions in scope, so use the efficient
            // top-level-values overload (newline is JSON whitespace, so '\n'-separated values parse
            // natively without a per-line StreamReader).
            sb.AppendLine("    public static IAsyncEnumerable<T?> ReadJsonLinesAsync<T>(");
            sb.AppendLine("        Stream stream,");
            sb.AppendLine("        JsonSerializerOptions options,");
            sb.AppendLine("        CancellationToken cancellationToken)");
            sb.AppendLine("        => JsonSerializer.DeserializeAsyncEnumerable<T>(stream, topLevelValues: true, options, cancellationToken);");
        }

        sb.AppendLine("}");

        return sb.ToString();
    }
}