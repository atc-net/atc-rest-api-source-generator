namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// An operation's own <c>x-</c> extensions on its endpoint: each one the generator does not read itself
/// (<c>x-audit: false</c>, <c>x-owner: { team: billing }</c>) becomes an <c>ApiOperationExtension</c> in the endpoint's
/// metadata, so a middleware or a filter can act on what the specification says next to the operation. The ones the
/// generator reads (<c>x-retry-*</c>, <c>x-ratelimit-*</c>, <c>x-cache-*</c>, <c>x-authorize-roles</c>, …) already shape
/// the endpoint and are left out. A scalar is its text (<c>false</c>, <c>3</c>, <c>Orders</c>); an object or a list
/// its compact JSON.
/// </summary>
public static class OperationExtensionMetadataExtractor
{
    /// <summary>
    /// The class name of the generated metadata type.
    /// </summary>
    public const string ClassName = "ApiOperationExtension";

    // The extension families the generator reads, and the single extensions it reads
    private static readonly string[] ReadPrefixes =
    [
        "x-atc-",
        "x-authentication-",
        "x-authorize-",
        "x-cache-",
        "x-ratelimit-",
        "x-retry-",
        "x-return-",
        "x-sse-",
        "x-signalr-",
    ];

    private static readonly HashSet<string> ReadNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "x-continuation",
        "x-enum-varnames",
        "x-implements",
        "x-multipart",
        "x-operation-response-cardinality",
        "x-pagination",
    };

    /// <summary>
    /// Whether the generator reads the extension itself.
    /// </summary>
    /// <param name="name">The extension name.</param>
    /// <returns>True for one of the generator's own extensions.</returns>
    public static bool IsReadByTheGenerator(string name)
        => name is not null &&
           (ReadNames.Contains(name) ||
            Array.Exists(ReadPrefixes, p => name.StartsWith(p, StringComparison.OrdinalIgnoreCase)));

    /// <summary>
    /// The extensions of an operation that go on its endpoint, by name.
    /// </summary>
    /// <param name="operation">The operation.</param>
    /// <returns>Each extension's name and value as text.</returns>
    public static IReadOnlyList<(string Name, string Value)> Collect(
        OpenApiOperation operation)
    {
        if (operation?.Extensions is not { Count: > 0 } extensions)
        {
            return [];
        }

        return extensions
            .Where(e => e.Key.StartsWith("x-", StringComparison.OrdinalIgnoreCase) && !IsReadByTheGenerator(e.Key))
            .Select(e => (e.Key, Value: e.Value is JsonNodeExtension { Node: { } node } ? TextOf(node) : null))
            .Where(e => e.Value is not null)
            .Select(e => (e.Key, e.Value!))
            .OrderBy(e => e.Key, StringComparer.Ordinal)
            .ToList();
    }

    /// <summary>
    /// The <c>.WithMetadata(…)</c> calls of an operation's extensions.
    /// </summary>
    /// <param name="operation">The operation.</param>
    /// <param name="projectName">The project name (root namespace).</param>
    /// <returns>One call per extension, without indentation.</returns>
    public static IReadOnlyList<string> MetadataCalls(
        OpenApiOperation operation,
        string projectName)
        => Collect(operation)
            .Select(e => $".WithMetadata(new global::{projectName}.Generated.{ClassName}({CSharpLiteralHelper.ToStringLiteral(e.Name)}, {CSharpLiteralHelper.ToStringLiteral(e.Value)}))")
            .ToList();

    /// <summary>
    /// Whether an operation or a webhook of the document has an extension that goes on its endpoint.
    /// </summary>
    /// <param name="openApiDoc">The specification.</param>
    /// <param name="includeDeprecated">Whether deprecated operations are generated.</param>
    /// <returns>True when the metadata type is needed.</returns>
    public static bool IsNeeded(
        OpenApiDocument openApiDoc,
        bool includeDeprecated)
        => openApiDoc is not null &&
           openApiDoc
               .GetAllOperationsAndWebhooks()
               .Any(o => (includeDeprecated || !o.Deprecated) && Collect(o).Count > 0);

    /// <summary>
    /// The source of the metadata type.
    /// </summary>
    /// <param name="projectName">The project name (root namespace).</param>
    /// <returns>The file content.</returns>
    public static string Generate(string projectName)
        => $$"""
             // <auto-generated />
             #nullable enable

             using System;
             using System.CodeDom.Compiler;

             namespace {{projectName}}.Generated;

             /// <summary>
             /// An <c>x-</c> extension the specification gives an operation, in its endpoint's metadata: a scalar as its text
             /// (<c>false</c>, <c>3</c>), an object or a list as its JSON. Read it with <see cref="Find"/>, or from
             /// <c>Endpoint.Metadata.GetOrderedMetadata&lt;{{ClassName}}&gt;()</c>.
             /// </summary>
             /// <param name="Name">The extension's name, as the specification writes it (<c>x-audit</c>).</param>
             /// <param name="Value">Its value as text.</param>
             [GeneratedCode("{{GeneratorInfo.Name}}", "{{GeneratorInfo.Version}}")]
             public sealed record {{ClassName}}(
                 string Name,
                 string Value)
             {
                 /// <summary>
                 /// The value of an extension on an endpoint.
                 /// </summary>
                 /// <param name="endpoint">The endpoint (<c>HttpContext.GetEndpoint()</c>).</param>
                 /// <param name="name">The extension's name (<c>x-audit</c>).</param>
                 /// <returns>Its value as text, or <see langword="null"/> when the operation does not have it.</returns>
                 public static string? Find(
                     global::Microsoft.AspNetCore.Http.Endpoint? endpoint,
                     string name)
                 {
                     if (endpoint is null)
                     {
                         return null;
                     }

                     foreach (var extension in endpoint.Metadata.GetOrderedMetadata<{{ClassName}}>())
                     {
                         if (string.Equals(extension.Name, name, StringComparison.Ordinal))
                         {
                             return extension.Value;
                         }
                     }

                     return null;
                 }
             }
             """;

    private static string? TextOf(JsonNode node)
        => node is JsonValue value
            ? value.TryGetValue<string>(out var text)
                ? text
                : value.ToJsonString()
            : node.ToJsonString();
}