namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// The <c>IApiResult</c> interface every generated <c>{Operation}Result</c> and webhook result implements: what a
/// handler test reads - <c>StatusCode</c>, <c>Value</c>, <c>Problem</c>, <c>Location</c> and <c>Headers</c> - so a
/// helper shared by the tests of every tag namespace takes one type.
/// </summary>
public static class ApiResultExtractor
{
    /// <summary>
    /// The interface's name in a type list (fully qualified).
    /// </summary>
    /// <param name="projectName">The project name (root namespace).</param>
    /// <returns>The reference.</returns>
    public static string InterfaceReference(string projectName)
        => $"global::{NamespaceBuilder.BuildBase(projectName)}.IApiResult";

    /// <summary>
    /// The file content.
    /// </summary>
    /// <param name="projectName">The project name (root namespace).</param>
    /// <returns>The source.</returns>
    public static string Generate(string projectName)
        => $$"""
             // <auto-generated />
             #nullable enable

             using System.CodeDom.Compiler;
             using System.Collections.Generic;
             using Microsoft.AspNetCore.Http;

             namespace {{NamespaceBuilder.BuildBase(projectName)}};

             /// <summary>
             /// A generated operation or webhook result: what it answers with, for a test - the status code, the value, the
             /// problem, the location and the headers - whichever operation and tag namespace it is of.
             /// </summary>
             [GeneratedCode("{{GeneratorInfo.Name}}", "{{GeneratorInfo.Version}}")]
             public interface IApiResult : IResult, INestedHttpResult, IStatusCodeHttpResult, IValueHttpResult
             {
                 /// <summary>
                 /// The problem the result answers with (a ValidationProblemDetails for field errors), else null.
                 /// </summary>
                 global::Microsoft.AspNetCore.Mvc.ProblemDetails? Problem { get; }

                 /// <summary>
                 /// The Location header the result writes, else null.
                 /// </summary>
                 string? Location { get; }

                 /// <summary>
                 /// The response headers the result writes, by name.
                 /// </summary>
                 IReadOnlyDictionary<string, string> Headers { get; }
             }
             """;
}