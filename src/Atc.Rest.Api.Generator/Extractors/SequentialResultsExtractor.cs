namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// Emits the generated server-side <c>Streaming/SequentialResults.cs</c> helper that the API
/// server uses to write OpenAPI 3.2 sequential (writer-based) streaming responses: JSON Lines
/// (<c>application/jsonl</c>), JSON Text Sequence (<c>application/json-seq</c>) and
/// multipart/mixed (<c>multipart/mixed</c>). The helper is emitted once per server project only
/// when an operation actually requires it.
/// </summary>
public static class SequentialResultsExtractor
{
    /// <summary>
    /// The multipart/mixed boundary token baked into the emitted server writer and used as the
    /// client-side fallback when a response omits an explicit <c>boundary</c> media-type parameter.
    /// Single generator-side source for the three emission sites (server const, typed-client
    /// fallback, per-operation-client fallback) so the emitted literal stays in lockstep.
    /// </summary>
    public const string MultipartBoundaryValue = "atc-stream-boundary";

    /// <summary>
    /// Determines whether the document declares any streaming operation, which needs the emitted
    /// server-side <c>SequentialResults</c> helper: the writer-based framings (JSON Lines, JSON Text
    /// Sequence, multipart/mixed) are written by it, and Server-Sent Events and a JSON array, written by
    /// the framework, are started through its <c>StartedStreamResult&lt;T&gt;</c>.
    /// </summary>
    /// <param name="openApiDoc">The OpenAPI document.</param>
    /// <returns>True when at least one operation requires the SequentialResults helper.</returns>
    public static bool DocumentRequiresSequentialResults(
        OpenApiDocument openApiDoc)
    {
        if (openApiDoc?.Paths is null)
        {
            return false;
        }

        foreach (var path in openApiDoc.Paths)
        {
            if (path.Value?.Operations is null)
            {
                continue;
            }

            foreach (var operation in path.Value.Operations)
            {
                if (operation.Value.IsStreamingResponse())
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Generates the source content for the server-side <c>Streaming/SequentialResults.cs</c>
    /// helper. The namespace is the server's generated root suffixed with <c>.Streaming</c>.
    /// Ships the JSON Lines (<c>WriteJsonLinesAsync</c> + <c>JsonLinesResult&lt;T&gt;</c>), JSON Text
    /// Sequence (<c>WriteJsonSequenceAsync</c> + <c>JsonSequenceResult&lt;T&gt;</c>) and multipart/mixed
    /// (<c>WriteMultipartMixedAsync</c> + <c>MultipartMixedResult&lt;T&gt;</c>) writers.
    /// </summary>
    /// <param name="projectName">The generated project name (the server root namespace prefix).</param>
    /// <returns>The full file content for the SequentialResults helper.</returns>
    public static string GenerateContent(string projectName)
        => TemplateText.Lines(
        [
            $$"""
            // <auto-generated />
            #nullable enable
            using System;
            using System.CodeDom.Compiler;
            using System.Collections.Generic;
            using System.Runtime.CompilerServices;
            using System.IO;
            using System.Text;
            using System.Text.Json;
            using System.Threading;
            using System.Threading.Tasks;
            using Microsoft.AspNetCore.Http;
            using Microsoft.AspNetCore.Http.Json;
            using Microsoft.Extensions.DependencyInjection;
            using Microsoft.Extensions.Options;

            namespace {{projectName}}.Generated.Streaming;

            [GeneratedCode("Atc.Rest.Api.SourceGenerator", "2.1.1")]
            public static class SequentialStreamWriter
            {
            """,

            // The newline separator is emitted via WriteAsync (NOT WriteByte): at runtime the stream is
            // Kestrel's Response.Body, which has AllowSynchronousIO=false by default, so the sync Write
            // that WriteByte performs throws InvalidOperationException. Cache the single byte to avoid
            // per-item allocation.
            $$"""
                private static readonly byte[] LineFeed = { (byte)'\n' };

            """,

            // RFC 7464 JSON Text Sequence record separator (0x1E), written before each record.
            $$"""
                private static readonly byte[] RecordSeparator = { 0x1E };

            """,

            // multipart/mixed boundary token + CRLF, used to frame each part.
            $$"""
                public const string MultipartBoundary = "atc-stream-boundary";

                private static readonly byte[] Crlf = { (byte)'\r', (byte)'\n' };

                private static readonly byte[] ArrayStart = { (byte)'[' };

                private static readonly byte[] ArraySeparator = { (byte)',' };

                private static readonly byte[] ArrayEnd = { (byte)']' };

            """,

            // One item per line, whatever the host's options say: an indented item would break a JSON Lines stream (and a
            // JSON Text Sequence or multipart part is easier read on one line too). The compact copy is cached per options
            // instance, so the serializer keeps its metadata cache.
            $$"""
                private static readonly global::System.Runtime.CompilerServices.ConditionalWeakTable<JsonSerializerOptions, JsonSerializerOptions> CompactOptions = new();

                private static JsonSerializerOptions Compact(JsonSerializerOptions options)
                    => options.WriteIndented
                        ? CompactOptions.GetValue(options, static o => new JsonSerializerOptions(o) { WriteIndented = false })
                        : options;

                public static async Task WriteJsonLinesAsync<T>(
                    IAsyncEnumerable<T> items,
                    Stream stream,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                {
                    var typeInfo = global::{{projectName}}.Generated.GeneratedJsonOptions.TypeInfo<T>(Compact(options));
                    await foreach (var item in items.WithCancellation(cancellationToken))
                    {
                        await JsonSerializer.SerializeAsync(stream, item, typeInfo, cancellationToken);
                        await stream.WriteAsync(LineFeed, cancellationToken);
                        await stream.FlushAsync(cancellationToken);
                    }
                }

            """,

            // A JSON array, one element at a time: '[' first, a comma before every element but the first, ']' last, each
            // element flushed as it is written
            $$"""
                public static async Task WriteJsonArrayAsync<T>(
                    IAsyncEnumerable<T> items,
                    Stream stream,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                {
                    var typeInfo = global::{{projectName}}.Generated.GeneratedJsonOptions.TypeInfo<T>(Compact(options));
                    await stream.WriteAsync(ArrayStart, cancellationToken);
                    var first = true;
                    await foreach (var item in items.WithCancellation(cancellationToken))
                    {
                        if (!first)
                        {
                            await stream.WriteAsync(ArraySeparator, cancellationToken);
                        }

                        first = false;
                        await JsonSerializer.SerializeAsync(stream, item, typeInfo, cancellationToken);
                        await stream.FlushAsync(cancellationToken);
                    }

                    await stream.WriteAsync(ArrayEnd, cancellationToken);
                    await stream.FlushAsync(cancellationToken);
                }

            """,

            // RFC 7464: each record is framed as RS(0x1E) <json> LF(0x0A). All writes are async for the
            // same Kestrel AllowSynchronousIO=false reason as the JSON Lines writer above.
            $$"""
                public static async Task WriteJsonSequenceAsync<T>(
                    IAsyncEnumerable<T> items,
                    Stream stream,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                {
                    var typeInfo = global::{{projectName}}.Generated.GeneratedJsonOptions.TypeInfo<T>(Compact(options));
                    await foreach (var item in items.WithCancellation(cancellationToken))
                    {
                        await stream.WriteAsync(RecordSeparator, cancellationToken);
                        await JsonSerializer.SerializeAsync(stream, item, typeInfo, cancellationToken);
                        await stream.WriteAsync(LineFeed, cancellationToken);
                        await stream.FlushAsync(cancellationToken);
                    }
                }

            """,

            // multipart/mixed: each part is `--<boundary>\r\nContent-Type: application/json\r\n\r\n<json>\r\n`,
            // terminated by `--<boundary>--\r\n`. All writes async (same Kestrel AllowSynchronousIO=false reason).
            $$"""
                public static async Task WriteMultipartMixedAsync<T>(
                    IAsyncEnumerable<T> items,
                    Stream stream,
                    string boundary,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                {
                    var typeInfo = global::{{projectName}}.Generated.GeneratedJsonOptions.TypeInfo<T>(Compact(options));
                    await foreach (var item in items.WithCancellation(cancellationToken))
                    {
                        var header = Encoding.ASCII.GetBytes($"--{boundary}\r\nContent-Type: application/json\r\n\r\n");
                        await stream.WriteAsync(header, cancellationToken);
                        await JsonSerializer.SerializeAsync(stream, item, typeInfo, cancellationToken);
                        await stream.WriteAsync(Crlf, cancellationToken);
                        await stream.FlushAsync(cancellationToken);
                    }

                    var closing = Encoding.ASCII.GetBytes($"--{boundary}--\r\n");
                    await stream.WriteAsync(closing, cancellationToken);
                    await stream.FlushAsync(cancellationToken);
                }
            }

            /// <summary>
            /// A stream of items as the elements of a JSON array, each written as it comes, after the status and headers.
            /// Its status code is 200 and its value the items, as the framework's <c>Ok&lt;T&gt;</c> would give them.
            /// </summary>
            [GeneratedCode("Atc.Rest.Api.SourceGenerator", "2.1.1")]
            public sealed class JsonArrayResult<T> : IResult, IStatusCodeHttpResult, IValueHttpResult
            {
                private readonly IAsyncEnumerable<T> items;

                public JsonArrayResult(IAsyncEnumerable<T> items)
                    => this.items = items;

                public int? StatusCode
                    => StatusCodes.Status200OK;

                public object? Value
                    => items;

                public async Task ExecuteAsync(HttpContext httpContext)
                {
