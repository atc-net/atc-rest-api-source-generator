namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// Emits the generated server-side <c>Streaming/SequentialResults.cs</c> helper that the API
/// server uses to write OpenAPI 3.2 sequential (writer-based) streaming responses — JSON Lines
/// today (<c>application/jsonl</c>), with JSON Text Sequence and multipart/mixed to follow.
/// The helper is emitted once per server project only when an operation actually requires it.
/// </summary>
public static class SequentialResultsExtractor
{
    /// <summary>
    /// Determines whether the document declares any streaming operation that needs the emitted
    /// server-side <c>SequentialResults</c> helper. That is any operation whose framing is one of
    /// the writer-based framings — <see cref="StreamingFraming.JsonLines"/>,
    /// <see cref="StreamingFraming.JsonSequence"/> or <see cref="StreamingFraming.MultipartMixed"/>.
    /// (Server-Sent Events use the first-party <c>TypedResults.ServerSentEvents</c> writer and the
    /// legacy JSON-array path uses <c>TypedResults.Ok</c>, so neither needs this helper.)
    /// </summary>
    /// <param name="openApiDoc">The OpenAPI document.</param>
    /// <returns>True when at least one operation requires the SequentialResults helper.</returns>
    public static bool DocumentRequiresSequentialResults(
        OpenApiDocument openApiDoc)
    {
        if (openApiDoc?.Paths == null)
        {
            return false;
        }

        foreach (var path in openApiDoc.Paths)
        {
            if (path.Value?.Operations == null)
            {
                continue;
            }

            foreach (var operation in path.Value.Operations)
            {
                if (!operation.Value.IsStreamingResponse())
                {
                    continue;
                }

                var framing = operation.Value.GetStreamingFraming();
                if (framing is StreamingFraming.JsonLines
                    or StreamingFraming.JsonSequence
                    or StreamingFraming.MultipartMixed)
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Generates the source content for the server-side <c>Streaming/SequentialResults.cs</c>
    /// helper. The namespace is the server's generated root suffixed with <c>.Streaming</c>.
    /// Ships the JSON Lines writer (<c>WriteJsonLinesAsync</c> + <c>JsonLinesResult&lt;T&gt;</c>)
    /// and the JSON Text Sequence writer (<c>WriteJsonSequenceAsync</c> + <c>JsonSequenceResult&lt;T&gt;</c>);
    /// a later task adds the multipart/mixed members.
    /// </summary>
    /// <param name="projectName">The generated project name (the server root namespace prefix).</param>
    /// <returns>The full file content for the SequentialResults helper.</returns>
    public static string GenerateContent(string projectName)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.CodeDom.Compiler;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.IO;");
        sb.AppendLine("using System.Text.Json;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Microsoft.AspNetCore.Http;");
        sb.AppendLine("using Microsoft.AspNetCore.Http.Json;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using Microsoft.Extensions.Options;");
        sb.AppendLine();
        sb.AppendLine($"namespace {projectName}.Generated.Streaming;");
        sb.AppendLine();
        sb.AppendLine($"[GeneratedCode(\"{GeneratorInfo.Name}\", \"{GeneratorInfo.Version}\")]");
        sb.AppendLine("public static class SequentialStreamWriter");
        sb.AppendLine("{");

        // The newline separator is emitted via WriteAsync (NOT WriteByte): at runtime the stream is
        // Kestrel's Response.Body, which has AllowSynchronousIO=false by default, so the sync Write
        // that WriteByte performs throws InvalidOperationException. Cache the single byte to avoid
        // per-item allocation.
        sb.AppendLine("    private static readonly byte[] LineFeed = { (byte)'\\n' };");
        sb.AppendLine();

        // RFC 7464 JSON Text Sequence record separator (0x1E), written before each record.
        sb.AppendLine("    private static readonly byte[] RecordSeparator = { 0x1E };");
        sb.AppendLine();
        sb.AppendLine("    public static async Task WriteJsonLinesAsync<T>(");
        sb.AppendLine("        IAsyncEnumerable<T> items,");
        sb.AppendLine("        Stream stream,");
        sb.AppendLine("        JsonSerializerOptions options,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        await foreach (var item in items.WithCancellation(cancellationToken))");
        sb.AppendLine("        {");
        sb.AppendLine("            await JsonSerializer.SerializeAsync(stream, item, options, cancellationToken);");
        sb.AppendLine("            await stream.WriteAsync(LineFeed, cancellationToken);");
        sb.AppendLine("            await stream.FlushAsync(cancellationToken);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        // RFC 7464: each record is framed as RS(0x1E) <json> LF(0x0A). All writes are async for the
        // same Kestrel AllowSynchronousIO=false reason as the JSON Lines writer above.
        sb.AppendLine("    public static async Task WriteJsonSequenceAsync<T>(");
        sb.AppendLine("        IAsyncEnumerable<T> items,");
        sb.AppendLine("        Stream stream,");
        sb.AppendLine("        JsonSerializerOptions options,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        await foreach (var item in items.WithCancellation(cancellationToken))");
        sb.AppendLine("        {");
        sb.AppendLine("            await stream.WriteAsync(RecordSeparator, cancellationToken);");
        sb.AppendLine("            await JsonSerializer.SerializeAsync(stream, item, options, cancellationToken);");
        sb.AppendLine("            await stream.WriteAsync(LineFeed, cancellationToken);");
        sb.AppendLine("            await stream.FlushAsync(cancellationToken);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"[GeneratedCode(\"{GeneratorInfo.Name}\", \"{GeneratorInfo.Version}\")]");
        sb.AppendLine("public sealed class JsonLinesResult<T> : IResult");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly IAsyncEnumerable<T> items;");
        sb.AppendLine();
        sb.AppendLine("    public JsonLinesResult(IAsyncEnumerable<T> items)");
        sb.AppendLine("        => this.items = items;");
        sb.AppendLine();
        sb.AppendLine("    public async Task ExecuteAsync(HttpContext httpContext)");
        sb.AppendLine("    {");
        sb.AppendLine("        httpContext.Response.ContentType = \"application/jsonl\";");

        // Resolve the application's configured JSON options via the options system. The previous
        // GetService(typeof(JsonOptions)) lookup always returned null because ConfigureHttpJsonOptions
        // registers JsonOptions via IOptions<>, not as a direct service — so it fell back to bare
        // defaults (PascalCase, enums-as-numbers), mismatching the rest of the API's serialization.
        sb.AppendLine("        var options = httpContext.RequestServices");
        sb.AppendLine("            .GetRequiredService<IOptions<JsonOptions>>()");
        sb.AppendLine("            .Value.SerializerOptions;");
        sb.AppendLine("        await SequentialStreamWriter.WriteJsonLinesAsync(items, httpContext.Response.Body, options, httpContext.RequestAborted);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"[GeneratedCode(\"{GeneratorInfo.Name}\", \"{GeneratorInfo.Version}\")]");
        sb.AppendLine("public sealed class JsonSequenceResult<T> : IResult");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly IAsyncEnumerable<T> items;");
        sb.AppendLine();
        sb.AppendLine("    public JsonSequenceResult(IAsyncEnumerable<T> items)");
        sb.AppendLine("        => this.items = items;");
        sb.AppendLine();
        sb.AppendLine("    public async Task ExecuteAsync(HttpContext httpContext)");
        sb.AppendLine("    {");
        sb.AppendLine("        httpContext.Response.ContentType = \"application/json-seq\";");

        // Same DI-configured JSON options lookup as JsonLinesResult (the C2 fix).
        sb.AppendLine("        var options = httpContext.RequestServices");
        sb.AppendLine("            .GetRequiredService<IOptions<JsonOptions>>()");
        sb.AppendLine("            .Value.SerializerOptions;");
        sb.AppendLine("        await SequentialStreamWriter.WriteJsonSequenceAsync(items, httpContext.Response.Body, options, httpContext.RequestAborted);");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }
}