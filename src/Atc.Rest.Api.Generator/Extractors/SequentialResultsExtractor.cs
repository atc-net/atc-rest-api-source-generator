namespace Atc.Rest.Api.Generator.Extractors;

/// <summary>
/// Emits the generated server-side <c>Streaming/SequentialResults.cs</c> helper that the API
/// server uses to write OpenAPI 3.2 sequential (writer-based) streaming responses: JSON Lines
/// (<c>application/jsonl</c>), JSON Text Sequence (<c>application/json-seq</c>) and
/// multipart/mixed (<c>multipart/mixed</c>). The helper is emitted once per server project only
/// when an operation actually requires it.
/// </summary>
public static class SequentialResultsExtractor
{
    /// <summary>
    /// The multipart/mixed boundary token baked into the emitted server writer and used as the
    /// client-side fallback when a response omits an explicit <c>boundary</c> media-type parameter.
    /// Single generator-side source for the three emission sites (server const, typed-client
    /// fallback, per-operation-client fallback) so the emitted literal stays in lockstep.
    /// </summary>
    public const string MultipartBoundaryValue = "atc-stream-boundary";

    /// <summary>
    /// Determines whether the document declares any streaming operation, which needs the emitted
    /// server-side <c>SequentialResults</c> helper: the writer-based framings (JSON Lines, JSON Text
    /// Sequence, multipart/mixed) are written by it, and Server-Sent Events and a JSON array, written by
    /// the framework, are started through its <c>StartedStreamResult&lt;T&gt;</c>.
    /// </summary>
    /// <param name="openApiDoc">The OpenAPI document.</param>
    /// <returns>True when at least one operation requires the SequentialResults helper.</returns>
    public static bool DocumentRequiresSequentialResults(
        OpenApiDocument openApiDoc)
    {
        if (openApiDoc?.Paths is null)
        {
            return false;
        }

        foreach (var path in openApiDoc.Paths)
        {
            if (path.Value?.Operations is null)
            {
                continue;
            }

            foreach (var operation in path.Value.Operations)
            {
                if (operation.Value.IsStreamingResponse())
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Generates the source content for the server-side <c>Streaming/SequentialResults.cs</c>
    /// helper. The namespace is the server's generated root suffixed with <c>.Streaming</c>.
    /// Ships the JSON Lines (<c>WriteJsonLinesAsync</c> + <c>JsonLinesResult&lt;T&gt;</c>), JSON Text
    /// Sequence (<c>WriteJsonSequenceAsync</c> + <c>JsonSequenceResult&lt;T&gt;</c>) and multipart/mixed
    /// (<c>WriteMultipartMixedAsync</c> + <c>MultipartMixedResult&lt;T&gt;</c>) writers.
    /// </summary>
    /// <param name="projectName">The generated project name (the server root namespace prefix).</param>
    /// <returns>The full file content for the SequentialResults helper.</returns>
    public static string GenerateContent(string projectName)
        => TemplateText.Lines(
        [
            $$"""
            // <auto-generated />
            #nullable enable
            using System;
            using System.CodeDom.Compiler;
            using System.Collections.Generic;
            using System.Runtime.CompilerServices;
            using System.IO;
            using System.Text;
            using System.Text.Json;
            using System.Threading;
            using System.Threading.Tasks;
            using Microsoft.AspNetCore.Http;
            using Microsoft.AspNetCore.Http.Json;
            using Microsoft.Extensions.DependencyInjection;
            using Microsoft.Extensions.Options;

            namespace {{projectName}}.Generated.Streaming;

            [GeneratedCode("{{GeneratorInfo.Name}}", "{{GeneratorInfo.Version}}")]
            public static class SequentialStreamWriter
            {
            """,

            // The newline separator is emitted via WriteAsync (NOT WriteByte): at runtime the stream is
            // Kestrel's Response.Body, which has AllowSynchronousIO=false by default, so the sync Write
            // that WriteByte performs throws InvalidOperationException. Cache the single byte to avoid
            // per-item allocation.
            $$"""
                private static readonly byte[] LineFeed = { (byte)'\n' };

            """,

            // A stream starts at its first item: an exception before it is still a problem answer (nothing has been sent),
            // a quiet stream gets its status and headers after a short wait
            $$"""
                /// <summary>
                /// How long a stream's first item is awaited before its status and headers are sent without it (one second
                /// by default): a stream that fails before its first item within this time is a problem answer, not a 200
                /// with a cut body; a quiet stream - one that waits for its first event - still gets its headers.
                /// </summary>
                public static TimeSpan FirstItemWait { get; set; } = TimeSpan.FromSeconds(1);

                /// <summary>
                /// The items, with the response started at the first: the status and headers go out with the first item,
                /// or - when it takes longer than <see cref="FirstItemWait"/> - before it. A client that leaves before the
                /// first item ends the reading with the cancellation; the handler's items are disposed once the item they
                /// were working on is done (an iterator cannot be disposed before).
                /// </summary>
                public static async IAsyncEnumerable<T> StartAtFirstItem<T>(
                    IAsyncEnumerable<T> items,
                    HttpResponse response,
                    [EnumeratorCancellation] CancellationToken cancellationToken = default)
                {
                    var enumerator = items.GetAsyncEnumerator(cancellationToken);
                    var first = enumerator.MoveNextAsync().AsTask();
                    try
                    {
                        bool hasFirst;
                        try
                        {
                            hasFirst = await first.WaitAsync(FirstItemWait, cancellationToken);
                        }
                        catch (TimeoutException)
                        {
                            await response.Body.FlushAsync(cancellationToken);
                            hasFirst = await first.WaitAsync(cancellationToken);
                        }

                        if (!hasFirst)
                        {
                            yield break;
                        }

                        yield return enumerator.Current;
                        while (await enumerator.MoveNextAsync())
                        {
                            yield return enumerator.Current;
                        }
                    }
                    finally
                    {
                        if (first.IsCompleted)
                        {
                            await enumerator.DisposeAsync();
                        }
                        else
                        {
                            _ = DisposeWhenDoneAsync(enumerator, first);
                        }
                    }
                }

                // The first item is still pending when the client left: dispose the items when it is done
                private static async Task DisposeWhenDoneAsync<T>(
                    IAsyncEnumerator<T> enumerator,
                    Task<bool> pending)
                {
                    try
                    {
                        await pending.ConfigureAwait(false);
                    }
                    catch (Exception)
                    {
                        // The item of a request that has gone - nothing to answer it to
                    }

                    try
                    {
                        await enumerator.DisposeAsync().ConfigureAwait(false);
                    }
                    catch (Exception)
                    {
                        // As above
                    }
                }

            """,

            // RFC 7464 JSON Text Sequence record separator (0x1E), written before each record.
            $$"""
                private static readonly byte[] RecordSeparator = { 0x1E };

            """,

            // multipart/mixed boundary token + CRLF, used to frame each part.
            $$"""
                public const string MultipartBoundary = "atc-stream-boundary";

                private static readonly byte[] Crlf = { (byte)'\r', (byte)'\n' };

                private static readonly byte[] ArrayStart = { (byte)'[' };

                private static readonly byte[] ArraySeparator = { (byte)',' };

                private static readonly byte[] ArrayEnd = { (byte)']' };

            """,

            // One item per line, whatever the host's options say: an indented item would break a JSON Lines stream (and a
            // JSON Text Sequence or multipart part is easier read on one line too). The compact copy is cached per options
            // instance, so the serializer keeps its metadata cache.
            $$"""
                private static readonly global::System.Runtime.CompilerServices.ConditionalWeakTable<JsonSerializerOptions, JsonSerializerOptions> CompactOptions = new();

                private static JsonSerializerOptions Compact(JsonSerializerOptions options)
                    => options.WriteIndented
                        ? CompactOptions.GetValue(options, static o => new JsonSerializerOptions(o) { WriteIndented = false })
                        : options;

                public static async Task WriteJsonLinesAsync<T>(
                    IAsyncEnumerable<T> items,
                    Stream stream,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                {
                    var typeInfo = global::{{projectName}}.Generated.GeneratedJsonOptions.TypeInfo<T>(Compact(options));
                    await foreach (var item in items.WithCancellation(cancellationToken))
                    {
                        await JsonSerializer.SerializeAsync(stream, item, typeInfo, cancellationToken);
                        await stream.WriteAsync(LineFeed, cancellationToken);
                        await stream.FlushAsync(cancellationToken);
                    }
                }

            """,

            // A JSON array, one element at a time: '[' first, a comma before every element but the first, ']' last, each
            // element flushed as it is written
            $$"""
                public static async Task WriteJsonArrayAsync<T>(
                    IAsyncEnumerable<T> items,
                    Stream stream,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                {
                    var typeInfo = global::{{projectName}}.Generated.GeneratedJsonOptions.TypeInfo<T>(Compact(options));
                    var first = true;
                    await foreach (var item in items.WithCancellation(cancellationToken))
                    {
                        await stream.WriteAsync(first ? ArrayStart : ArraySeparator, cancellationToken);
                        first = false;
                        await JsonSerializer.SerializeAsync(stream, item, typeInfo, cancellationToken);
                        await stream.FlushAsync(cancellationToken);
                    }

                    if (first)
                    {
                        await stream.WriteAsync(ArrayStart, cancellationToken);
                    }

                    await stream.WriteAsync(ArrayEnd, cancellationToken);
                    await stream.FlushAsync(cancellationToken);
                }

            """,

            // RFC 7464: each record is framed as RS(0x1E) <json> LF(0x0A). All writes are async for the
            // same Kestrel AllowSynchronousIO=false reason as the JSON Lines writer above.
            $$"""
                public static async Task WriteJsonSequenceAsync<T>(
                    IAsyncEnumerable<T> items,
                    Stream stream,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                {
                    var typeInfo = global::{{projectName}}.Generated.GeneratedJsonOptions.TypeInfo<T>(Compact(options));
                    await foreach (var item in items.WithCancellation(cancellationToken))
                    {
                        await stream.WriteAsync(RecordSeparator, cancellationToken);
                        await JsonSerializer.SerializeAsync(stream, item, typeInfo, cancellationToken);
                        await stream.WriteAsync(LineFeed, cancellationToken);
                        await stream.FlushAsync(cancellationToken);
                    }
                }

            """,

            // multipart/mixed: each part is `--<boundary>\r\nContent-Type: application/json\r\n\r\n<json>\r\n`,
            // terminated by `--<boundary>--\r\n`. All writes async (same Kestrel AllowSynchronousIO=false reason).
            $$"""
                public static async Task WriteMultipartMixedAsync<T>(
                    IAsyncEnumerable<T> items,
                    Stream stream,
                    string boundary,
                    JsonSerializerOptions options,
                    CancellationToken cancellationToken)
                {
                    var typeInfo = global::{{projectName}}.Generated.GeneratedJsonOptions.TypeInfo<T>(Compact(options));
                    await foreach (var item in items.WithCancellation(cancellationToken))
                    {
                        var header = Encoding.ASCII.GetBytes($"--{boundary}\r\nContent-Type: application/json\r\n\r\n");
                        await stream.WriteAsync(header, cancellationToken);
                        await JsonSerializer.SerializeAsync(stream, item, typeInfo, cancellationToken);
                        await stream.WriteAsync(Crlf, cancellationToken);
                        await stream.FlushAsync(cancellationToken);
                    }

                    var closing = Encoding.ASCII.GetBytes($"--{boundary}--\r\n");
                    await stream.WriteAsync(closing, cancellationToken);
                    await stream.FlushAsync(cancellationToken);
                }
            }

            /// <summary>
            /// A stream of items as the elements of a JSON array, each written as it comes; the response starts at the first
            /// (see <see cref="SequentialStreamWriter.FirstItemWait"/>).
            /// Its status code is 200 and its value the items, as the framework's <c>Ok&lt;T&gt;</c> would give them.
            /// </summary>
            [GeneratedCode("{{GeneratorInfo.Name}}", "{{GeneratorInfo.Version}}")]
            public sealed class JsonArrayResult<T> : IResult, IStatusCodeHttpResult, IValueHttpResult
            {
                private readonly IAsyncEnumerable<T> items;

                public JsonArrayResult(IAsyncEnumerable<T> items)
                    => this.items = items;

                public int? StatusCode
                    => StatusCodes.Status200OK;

                public object? Value
                    => items;

                public async Task ExecuteAsync(HttpContext httpContext)
                {
                    httpContext.Response.ContentType = "application/json; charset=utf-8";
                    var options = httpContext.RequestServices
                        .GetRequiredService<IOptions<JsonOptions>>()
                        .Value.SerializerOptions;
                    await SequentialStreamWriter.WriteJsonArrayAsync(SequentialStreamWriter.StartAtFirstItem(items, httpContext.Response, httpContext.RequestAborted), httpContext.Response.Body, options, httpContext.RequestAborted);
                }
            }

            [GeneratedCode("{{GeneratorInfo.Name}}", "{{GeneratorInfo.Version}}")]
            public sealed class JsonLinesResult<T> : IResult, IStatusCodeHttpResult, IValueHttpResult
            {
                private readonly IAsyncEnumerable<T> items;
                private readonly string contentType;

                public int? StatusCode
                    => StatusCodes.Status200OK;

                public object? Value
                    => items;

            """,

            // The media type the specification declares (application/x-ndjson, application/geo+json-seq, ...): the
            // response says what the document promised
            $$"""
                public JsonLinesResult(IAsyncEnumerable<T> items)
                    : this(items, "application/jsonl")
                {
                }

                public JsonLinesResult(
                    IAsyncEnumerable<T> items,
                    string contentType)
                {
                    this.items = items;
                    this.contentType = contentType;
                }

                public async Task ExecuteAsync(HttpContext httpContext)
                {
                    httpContext.Response.ContentType = contentType;
            """,

            // Resolve the application's configured JSON options via the options system. The previous
            // GetService(typeof(JsonOptions)) lookup always returned null because ConfigureHttpJsonOptions
            // registers JsonOptions via IOptions<>, not as a direct service — so it fell back to bare
            // defaults (PascalCase, enums-as-numbers), mismatching the rest of the API's serialization.
            $$"""
                    var options = httpContext.RequestServices
                        .GetRequiredService<IOptions<JsonOptions>>()
                        .Value.SerializerOptions;
                    await SequentialStreamWriter.WriteJsonLinesAsync(SequentialStreamWriter.StartAtFirstItem(items, httpContext.Response, httpContext.RequestAborted), httpContext.Response.Body, options, httpContext.RequestAborted);
                }
            }

            [GeneratedCode("{{GeneratorInfo.Name}}", "{{GeneratorInfo.Version}}")]
            public sealed class JsonSequenceResult<T> : IResult, IStatusCodeHttpResult, IValueHttpResult
            {
                private readonly IAsyncEnumerable<T> items;
                private readonly string contentType;

                public int? StatusCode
                    => StatusCodes.Status200OK;

                public object? Value
                    => items;

            """,

            // The media type the specification declares (application/x-ndjson, application/geo+json-seq, ...): the
            // response says what the document promised
            $$"""
                public JsonSequenceResult(IAsyncEnumerable<T> items)
                    : this(items, "application/json-seq")
                {
                }

                public JsonSequenceResult(
                    IAsyncEnumerable<T> items,
                    string contentType)
                {
                    this.items = items;
                    this.contentType = contentType;
                }

                public async Task ExecuteAsync(HttpContext httpContext)
                {
                    httpContext.Response.ContentType = contentType;
            """,

            // Same DI-configured JSON options lookup as JsonLinesResult.
            $$"""
                    var options = httpContext.RequestServices
                        .GetRequiredService<IOptions<JsonOptions>>()
                        .Value.SerializerOptions;
                    await SequentialStreamWriter.WriteJsonSequenceAsync(SequentialStreamWriter.StartAtFirstItem(items, httpContext.Response, httpContext.RequestAborted), httpContext.Response.Body, options, httpContext.RequestAborted);
                }
            }

            [GeneratedCode("{{GeneratorInfo.Name}}", "{{GeneratorInfo.Version}}")]
            public sealed class MultipartMixedResult<T> : IResult, IStatusCodeHttpResult, IValueHttpResult
            {
                private readonly IAsyncEnumerable<T> items;

                public MultipartMixedResult(IAsyncEnumerable<T> items)
                    => this.items = items;

                public int? StatusCode
                    => StatusCodes.Status200OK;

                public object? Value
                    => items;

                public async Task ExecuteAsync(HttpContext httpContext)
                {
                    httpContext.Response.ContentType = $"multipart/mixed; boundary={SequentialStreamWriter.MultipartBoundary}";
            """,

            // Same DI-configured JSON options lookup as the other result types.
            $$"""
                    var options = httpContext.RequestServices
                        .GetRequiredService<IOptions<JsonOptions>>()
                        .Value.SerializerOptions;
                    await SequentialStreamWriter.WriteMultipartMixedAsync(SequentialStreamWriter.StartAtFirstItem(items, httpContext.Response, httpContext.RequestAborted), httpContext.Response.Body, SequentialStreamWriter.MultipartBoundary, options, httpContext.RequestAborted);
                }
            }

            """,

            // Server-Sent Events are written by the framework, which sends the headers with the first item: the items are
            // handed to it through an enumerable that starts the response when the writer asks for the first
            $$"""
            /// <summary>
            /// A stream written by the framework (Server-Sent Events) that starts its response at the first item, or -
            /// when it takes longer than <see cref="SequentialStreamWriter.FirstItemWait"/> - before it: an exception before
            /// the first item is a problem answer, a quiet stream still gets its headers. Its status code is the framework
            /// result's (<see cref="Result"/>), and its value the items.
            /// </summary>
            [GeneratedCode("{{GeneratorInfo.Name}}", "{{GeneratorInfo.Version}}")]
            public sealed class StartedStreamResult<T> : IResult, IStatusCodeHttpResult, IValueHttpResult, INestedHttpResult
            {
                private readonly IAsyncEnumerable<T> items;
                private readonly Func<IAsyncEnumerable<T>, IResult> write;

                public StartedStreamResult(
                    IAsyncEnumerable<T> items,
                    Func<IAsyncEnumerable<T>, IResult> write)
                {
                    this.items = items;
                    this.write = write;
                    Result = write(items);
                }

                public IResult Result { get; }

                public int? StatusCode
                    => (Result as IStatusCodeHttpResult)?.StatusCode ?? StatusCodes.Status200OK;

                // The framework's Server-Sent Events result has no value of its own: the items
                public object? Value
                    => (Result as IValueHttpResult)?.Value ?? items;

                public Task ExecuteAsync(HttpContext httpContext)
                    => write(SequentialStreamWriter.StartAtFirstItem(items, httpContext.Response, httpContext.RequestAborted)).ExecuteAsync(httpContext);
            }
            """,
        ]);
}